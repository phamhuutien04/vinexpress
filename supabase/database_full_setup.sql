-- 1. Danh sách kho và kho trung tâm của nó.
SELECT kh.ma_kho, kh.ten_kho, kh.cap_kho, kv.tinh_thanh, kv.phuong_xa,
       trung_tam.ma_kho AS ma_kho_trung_tam
FROM public.kho_hang kh
JOIN public.khu_vuc kv ON kv.id = kh.khu_vuc_id
LEFT JOIN public.kho_hang trung_tam ON trung_tam.id = kh.kho_trung_tam_id
ORDER BY kv.tinh_thanh, kh.cap_kho, kh.ma_kho;

-- 2. Tuyến vận chuyển của các đơn xe tải.
SELECT dh.ma_van_don,
       kho_gui.ma_kho AS kho_nhan_gui,
       trung_tam_gui.ma_kho AS trung_tam_gui,
       trung_tam_dich.ma_kho AS trung_tam_dich,
       kho_dich.ma_kho AS kho_giao_nhan,
       dh.trang_thai
FROM public.don_hang dh
LEFT JOIN public.kho_hang kho_gui ON kho_gui.id = dh.kho_gui_id
LEFT JOIN public.kho_hang trung_tam_gui ON trung_tam_gui.id = dh.kho_trung_tam_gui_id
LEFT JOIN public.kho_hang trung_tam_dich ON trung_tam_dich.id = dh.kho_trung_tam_dich_id
LEFT JOIN public.kho_hang kho_dich ON kho_dich.id = dh.kho_dich_id
WHERE dh.phuong_tien = 'XE_TAI'
ORDER BY dh.ngay_tao DESC;
