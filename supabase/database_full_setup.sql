-- Kho cấp 2 chỉ được nối với kho cấp 1 trong cùng tỉnh/thành.
CREATE OR REPLACE FUNCTION public.kiem_tra_cay_kho()
RETURNS TRIGGER LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
    v_cap_trung_tam SMALLINT;
    v_tinh_kho TEXT;
    v_tinh_trung_tam TEXT;
BEGIN
    IF NEW.cap_kho = 1 THEN
        NEW.kho_trung_tam_id := NULL;
        RETURN NEW;
    END IF;
    SELECT kh.cap_kho, kv.tinh_thanh
    INTO v_cap_trung_tam, v_tinh_trung_tam
    FROM public.kho_hang kh JOIN public.khu_vuc kv ON kv.id = kh.khu_vuc_id
    WHERE kh.id = NEW.kho_trung_tam_id;
    SELECT tinh_thanh INTO v_tinh_kho FROM public.khu_vuc WHERE id = NEW.khu_vuc_id;
    IF NEW.cap_kho <> 2 OR v_cap_trung_tam <> 1
       OR v_tinh_kho IS DISTINCT FROM v_tinh_trung_tam THEN
        RAISE EXCEPTION 'Kho cấp 2 phải liên kết với một kho cấp 1 cùng tỉnh/thành';
    END IF;
    RETURN NEW;
END;
$$;

