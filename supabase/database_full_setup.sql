    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten_khu_vuc TEXT NOT NULL,
    tinh_thanh TEXT NOT NULL,
    phuong_xa TEXT NOT NULL,
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_khu_vuc_hanh_chinh UNIQUE (ten_khu_vuc, tinh_thanh, phuong_xa)
);

CREATE TABLE IF NOT EXISTS public.kho_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_kho VARCHAR(30) NOT NULL UNIQUE,
    ten_kho TEXT NOT NULL,
    dia_chi TEXT NOT NULL,
    khu_vuc_id BIGINT NOT NULL REFERENCES public.khu_vuc(id),
    so_dien_thoai VARCHAR(20),
    trang_thai VARCHAR(20) NOT NULL DEFAULT 'HOAT_DONG',
    cap_kho SMALLINT NOT NULL DEFAULT 1,
    kho_trung_tam_id BIGINT REFERENCES public.kho_hang(id),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_kho_hang_trang_thai CHECK (trang_thai IN ('HOAT_DONG', 'TAM_NGUNG')),
    CONSTRAINT chk_kho_hang_cap_kho CHECK (
        (cap_kho = 1 AND kho_trung_tam_id IS NULL)
        OR (cap_kho = 2 AND kho_trung_tam_id IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.don_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_van_don VARCHAR(30) NOT NULL UNIQUE,
    ma_qr UUID NOT NULL DEFAULT gen_random_uuid(),
    khach_hang_id BIGINT NOT NULL REFERENCES public.khach_hang(id),
    nguoi_gui_ten TEXT NOT NULL,
    nguoi_gui_dia_chi TEXT NOT NULL,
    nguoi_gui_sdt VARCHAR(20) NOT NULL,
    nguoi_nhan_ten TEXT NOT NULL,
    nguoi_nhan_dia_chi TEXT NOT NULL,
    nguoi_nhan_sdt VARCHAR(20) NOT NULL,
    can_nang NUMERIC(12,2) NOT NULL,
    gia_tri_hang NUMERIC(14,2) NOT NULL DEFAULT 0,
    phi_van_chuyen NUMERIC(14,2) NOT NULL DEFAULT 0,
    cod NUMERIC(14,2) NOT NULL DEFAULT 0,
    kho_gui_id BIGINT REFERENCES public.kho_hang(id),
    kho_dich_id BIGINT REFERENCES public.kho_hang(id),
    kho_trung_tam_gui_id BIGINT REFERENCES public.kho_hang(id),
    kho_trung_tam_dich_id BIGINT REFERENCES public.kho_hang(id),
    khoang_cach_km NUMERIC(12,2),
    phuong_tien VARCHAR(30),
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_LAY_HANG',
    ghi_chu TEXT,
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_don_hang_phuong_tien
        CHECK (phuong_tien IS NULL OR phuong_tien IN ('XE_MAY', 'XE_TAI')),
    CONSTRAINT chk_don_hang_kho CHECK (
        (phuong_tien = 'XE_MAY' AND khoang_cach_km <= 50
            AND kho_gui_id IS NULL AND kho_dich_id IS NULL)
        OR (phuong_tien = 'XE_TAI' AND khoang_cach_km > 50
            AND kho_gui_id IS NOT NULL AND kho_dich_id IS NOT NULL
            AND kho_gui_id <> kho_dich_id
            AND kho_trung_tam_gui_id IS NOT NULL
            AND kho_trung_tam_dich_id IS NOT NULL)
        OR (phuong_tien IS NULL AND khoang_cach_km IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_khu_vuc_dia_ban
    ON public.khu_vuc (tinh_thanh, phuong_xa);
CREATE INDEX IF NOT EXISTS idx_kho_hang_khu_vuc ON public.kho_hang (khu_vuc_id);
