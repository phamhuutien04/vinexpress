FOR UPDATE TO authenticated USING (auth.uid() = auth_user_id) WITH CHECK (auth.uid() = auth_user_id);
GRANT SELECT, UPDATE ON public.khach_hang TO authenticated;
REVOKE ALL ON FUNCTION public.tim_kho_theo_dia_chi(TEXT, BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.tim_kho_trung_tam(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.tao_don_hang_khach_hang(
    TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, NUMERIC, NUMERIC, NUMERIC, NUMERIC, NUMERIC, TEXT
) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.tao_don_hang_khach_hang(
    TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, NUMERIC, NUMERIC, NUMERIC, NUMERIC, NUMERIC, TEXT
) TO authenticated;

COMMIT;

