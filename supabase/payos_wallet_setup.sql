    BIGINT, TEXT, TEXT, NUMERIC, JSONB
) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.trang_thai_giao_dich_payos(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.huy_giao_dich_payos_nap_vi(BIGINT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.tao_giao_dich_payos_nap_vi(BIGINT) TO authenticated;
