    BIGINT, TEXT, TEXT, NUMERIC, JSONB
) TO service_role;
GRANT EXECUTE ON FUNCTION public.trang_thai_giao_dich_payos(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.huy_giao_dich_payos_nap_vi(BIGINT) TO authenticated;

