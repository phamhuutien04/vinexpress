CREATE SEQUENCE IF NOT EXISTS public.payos_ma_don_hang_seq START WITH 100000;

CREATE TABLE IF NOT EXISTS public.giao_dich_payos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    yeu_cau_nap_rut_id BIGINT NOT NULL UNIQUE
        REFERENCES public.yeu_cau_nap_rut_vi(id) ON DELETE RESTRICT,
    ma_don_payos BIGINT NOT NULL UNIQUE,
    so_tien NUMERIC(14,2) NOT NULL CHECK (so_tien > 0),
    payment_link_id TEXT UNIQUE,
    checkout_url TEXT,
    ma_tham_chieu TEXT,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_THANH_TOAN'
        CHECK (trang_thai IN ('CHO_THANH_TOAN', 'DA_THANH_TOAN', 'DA_HUY', 'LOI')),
    du_lieu_webhook JSONB,
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_thanh_toan TIMESTAMPTZ,
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_giao_dich_payos_ma_don
    ON public.giao_dich_payos(ma_don_payos);

REVOKE ALL ON TABLE public.giao_dich_payos FROM anon, authenticated;

-- Edge Function gọi hàm này dưới JWT của chính người dùng để tạo bản ghi chờ.
CREATE OR REPLACE FUNCTION public.tao_giao_dich_payos_nap_vi(
    p_yeu_cau_nap_rut_id BIGINT
)
RETURNS TABLE (id BIGINT, ma_don_payos BIGINT, so_tien NUMERIC)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_yeu_cau public.yeu_cau_nap_rut_vi%ROWTYPE;
BEGIN
    SELECT yc.* INTO v_yeu_cau
    FROM public.yeu_cau_nap_rut_vi yc
    JOIN public.vi v ON v.id = yc.vi_id
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE yc.id = p_yeu_cau_nap_rut_id
      AND (kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid())
    FOR UPDATE OF yc;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Không tìm thấy yêu cầu nạp ví của bạn';
    END IF;
    IF v_yeu_cau.loai <> 'NAP_TIEN'
       OR v_yeu_cau.phuong_thuc <> 'PAYOS'
       OR v_yeu_cau.trang_thai <> 'CHO_DUYET' THEN
        RAISE EXCEPTION 'Yêu cầu nạp ví không còn hợp lệ để thanh toán PayOS';
    END IF;

    RETURN QUERY
    INSERT INTO public.giao_dich_payos(
        yeu_cau_nap_rut_id, ma_don_payos, so_tien
    ) VALUES (
        v_yeu_cau.id, nextval('public.payos_ma_don_hang_seq'), v_yeu_cau.so_tien
    )
    RETURNING giao_dich_payos.id, giao_dich_payos.ma_don_payos,
              giao_dich_payos.so_tien;
END;
$$;

-- Chỉ Edge Function webhook (service_role) có quyền chốt thanh toán.
CREATE OR REPLACE FUNCTION public.xac_nhan_giao_dich_payos_nap_vi(
    p_ma_don_payos BIGINT,
    p_payment_link_id TEXT,
    p_ma_tham_chieu TEXT,
    p_so_tien NUMERIC,
    p_du_lieu_webhook JSONB DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_giao_dich public.giao_dich_payos%ROWTYPE;
    v_yeu_cau public.yeu_cau_nap_rut_vi%ROWTYPE;
BEGIN
    IF auth.role() <> 'service_role' THEN
        RAISE EXCEPTION 'Chỉ hệ thống PayOS được xác nhận thanh toán';
    END IF;

    SELECT * INTO v_giao_dich
    FROM public.giao_dich_payos
    WHERE ma_don_payos = p_ma_don_payos
    FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Không tìm thấy giao dịch PayOS';
    END IF;
    IF v_giao_dich.trang_thai = 'DA_THANH_TOAN' THEN
        RETURN; -- Webhook PayOS có thể gửi lại; không cộng tiền lần hai.
    END IF;
    IF v_giao_dich.trang_thai <> 'CHO_THANH_TOAN' THEN
        RAISE EXCEPTION 'Giao dịch PayOS không còn chờ thanh toán';
    END IF;
    IF ROUND(COALESCE(p_so_tien, 0), 0) <> ROUND(v_giao_dich.so_tien, 0) THEN
        RAISE EXCEPTION 'Số tiền PayOS không khớp';
    END IF;

    SELECT * INTO v_yeu_cau
    FROM public.yeu_cau_nap_rut_vi
    WHERE id = v_giao_dich.yeu_cau_nap_rut_id
    FOR UPDATE;
    IF NOT FOUND OR v_yeu_cau.trang_thai <> 'CHO_DUYET' THEN
        RAISE EXCEPTION 'Yêu cầu nạp ví không còn chờ thanh toán';
    END IF;

    -- Không phụ thuộc trigger cấu hình cũ: webhook cộng ví và ghi sổ cái trong
    -- cùng transaction, nên tiền PayOS đã xác nhận luôn phản ánh đúng trên ví.
    UPDATE public.vi
    SET so_du = so_du + v_yeu_cau.so_tien,
        ngay_cap_nhat = NOW()
    WHERE id = v_yeu_cau.vi_id;

    UPDATE public.yeu_cau_nap_rut_vi
    SET trang_thai = 'DA_DUYET', ngay_xu_ly = NOW()
    WHERE id = v_yeu_cau.id;

    INSERT INTO public.giao_dich_vi(
        vi_id, yeu_cau_nap_rut_id, loai, so_tien, so_du_sau, noi_dung
    )
    SELECT v.id, v_yeu_cau.id, 'NAP_TIEN', v_yeu_cau.so_tien, v.so_du,
           'Nạp tiền PayOS đã xác nhận'
    FROM public.vi v
    WHERE v.id = v_yeu_cau.vi_id;

    UPDATE public.giao_dich_payos
    SET trang_thai = 'DA_THANH_TOAN',
        payment_link_id = COALESCE(NULLIF(BTRIM(p_payment_link_id), ''), payment_link_id),
        ma_tham_chieu = NULLIF(BTRIM(p_ma_tham_chieu), ''),
        du_lieu_webhook = p_du_lieu_webhook,
        ngay_thanh_toan = NOW(),
        ngay_cap_nhat = NOW()
    WHERE id = v_giao_dich.id;
END;
$$;

-- Ứng dụng dùng hàm này để tự đóng QR ngay khi webhook đã chốt giao dịch.
CREATE OR REPLACE FUNCTION public.trang_thai_giao_dich_payos(
    p_ma_don_payos BIGINT
)
RETURNS TABLE (trang_thai VARCHAR, so_tien NUMERIC)
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
    SELECT gp.trang_thai, gp.so_tien
    FROM public.giao_dich_payos gp
    JOIN public.yeu_cau_nap_rut_vi yc ON yc.id = gp.yeu_cau_nap_rut_id
    JOIN public.vi v ON v.id = yc.vi_id
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE gp.ma_don_payos = p_ma_don_payos
      AND (kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid());
$$;

-- Người tạo giao dịch có thể hủy QR chưa thanh toán; webhook sau đó không thể
-- cộng tiền cho link đã hủy.
CREATE OR REPLACE FUNCTION public.huy_giao_dich_payos_nap_vi(
    p_ma_don_payos BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_giao_dich public.giao_dich_payos%ROWTYPE;
BEGIN
    SELECT gp.* INTO v_giao_dich
    FROM public.giao_dich_payos gp
    JOIN public.yeu_cau_nap_rut_vi yc ON yc.id = gp.yeu_cau_nap_rut_id
    JOIN public.vi v ON v.id = yc.vi_id
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE gp.ma_don_payos = p_ma_don_payos
      AND (kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid())
    FOR UPDATE OF gp;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Không tìm thấy giao dịch PayOS của bạn';
    END IF;
    IF v_giao_dich.trang_thai = 'DA_THANH_TOAN' THEN
        RAISE EXCEPTION 'Giao dịch đã thanh toán, không thể hủy';
    END IF;
    IF v_giao_dich.trang_thai <> 'CHO_THANH_TOAN' THEN
        RETURN;
    END IF;

    UPDATE public.giao_dich_payos
    SET trang_thai = 'DA_HUY', ngay_cap_nhat = NOW()
    WHERE id = v_giao_dich.id;

    UPDATE public.yeu_cau_nap_rut_vi
    SET trang_thai = 'TU_CHOI',
        ly_do_tu_choi = 'Khách hàng hủy thanh toán PayOS',
        ngay_xu_ly = NOW()
    WHERE id = v_giao_dich.yeu_cau_nap_rut_id
      AND trang_thai = 'CHO_DUYET';
END;
$$;

-- Không cho admin duyệt tay giao dịch PayOS vì chỉ webhook đã xác thực mới được cộng tiền.
CREATE OR REPLACE FUNCTION public.chan_duyet_tay_nap_vi_payos()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = public
AS $$
BEGIN
    IF NEW.loai = 'NAP_TIEN'
       AND NEW.phuong_thuc = 'PAYOS'
       AND NEW.trang_thai = 'DA_DUYET'
       AND auth.role() <> 'service_role' THEN
        RAISE EXCEPTION 'Giao dịch PayOS chỉ được xác nhận tự động từ webhook';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_chan_duyet_tay_nap_vi_payos
    ON public.yeu_cau_nap_rut_vi;
CREATE TRIGGER trg_chan_duyet_tay_nap_vi_payos
BEFORE UPDATE OF trang_thai ON public.yeu_cau_nap_rut_vi
FOR EACH ROW EXECUTE FUNCTION public.chan_duyet_tay_nap_vi_payos();

-- Hàm duyệt nạp ví đã tự cộng số dư. Bỏ trigger cũ để tránh cộng trùng nếu
-- patch_wallet_topup_approval.sql từng được chạy trong môi trường trước đó.
DROP TRIGGER IF EXISTS trg_cong_tien_khi_duyet_nap_vi
    ON public.yeu_cau_nap_rut_vi;

REVOKE ALL ON FUNCTION public.tao_giao_dich_payos_nap_vi(BIGINT) FROM PUBLIC;
