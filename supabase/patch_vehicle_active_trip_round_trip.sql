CREATE OR REPLACE FUNCTION public.quan_ly_kho_gan_xe_tao_chuyen(
  p_kho_di_id BIGINT,p_kho_den_id BIGINT,p_xe_id BIGINT,
  p_ngay_du_kien TIMESTAMPTZ DEFAULT NULL
) RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_nv_id BIGINT;
  v_chuyen_id BIGINT;
  v_ma VARCHAR;
  v_cap_di SMALLINT;
  v_kho_cha BIGINT;
BEGIN
  IF p_kho_di_id=p_kho_den_id THEN
    RAISE EXCEPTION 'Kho đi và kho đến phải khác nhau';
  END IF;
  IF NOT public.quan_ly_kho_duoc_quan_ly(p_kho_di_id) THEN
    RAISE EXCEPTION 'Bạn không quản lý kho khởi hành';
  END IF;

  SELECT nv.id INTO v_nv_id
  FROM public.nhan_vien nv
  WHERE nv.auth_user_id=auth.uid()
    AND nv.vai_tro='QUAN_LY_KHO'
    AND nv.trang_thai_duyet='DA_DUYET'
    AND nv.trang_thai='HOAT_DONG';
  IF v_nv_id IS NULL THEN
    RAISE EXCEPTION 'Tài khoản không phải quản lý kho';
  END IF;

  SELECT kh.cap_kho,kh.kho_trung_tam_id
  INTO v_cap_di,v_kho_cha
  FROM public.kho_hang kh
  WHERE kh.id=p_kho_di_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy kho khởi hành'; END IF;
  IF v_cap_di=2 AND p_kho_den_id<>v_kho_cha THEN
    RAISE EXCEPTION 'Kho cấp 2 chỉ được tạo chuyến lên kho cấp 1 trực thuộc';
  END IF;
  IF NOT EXISTS(
    SELECT 1 FROM public.quan_ly_kho_danh_sach_kho_den(p_kho_di_id) d
    WHERE d.id=p_kho_den_id
  ) THEN
    RAISE EXCEPTION 'Kho đến không đúng tuyến được phép';
  END IF;

  -- Khóa bản ghi xe trước khi kiểm tra để chống hai quản lý gán cùng lúc.
  PERFORM 1 FROM public.xe x WHERE x.id=p_xe_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy xe'; END IF;

  IF NOT EXISTS(
    SELECT 1 FROM public.xe x
    JOIN public.nhan_vien tx ON tx.id=x.tai_xe_id
    WHERE x.id=p_xe_id
      AND x.trang_thai='SAN_SANG'
      AND tx.vai_tro='VAN_CHUYEN'
      AND tx.kho_hang_id=p_kho_di_id
      AND tx.trang_thai_duyet='DA_DUYET'
      AND tx.trang_thai='HOAT_DONG'
  ) THEN
    RAISE EXCEPTION 'Xe không sẵn sàng hoặc không thuộc kho này';
  END IF;
  IF EXISTS(
    SELECT 1 FROM public.chuyen_xe cx
    WHERE cx.xe_id=p_xe_id
      AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
  ) THEN
    RAISE EXCEPTION 'Xe đang có chuyến chưa hoàn thành, không thể gán thêm chuyến';
  END IF;

  v_ma := 'CX' || TO_CHAR(NOW(),'YYMMDDHH24MISS')
    || UPPER(SUBSTR(REPLACE(gen_random_uuid()::TEXT,'-',''),1,5));
  INSERT INTO public.chuyen_xe(xe_id,ma_chuyen,trang_thai,ngay_du_kien)
  VALUES(p_xe_id,v_ma,'CHO_KHOI_HANH',p_ngay_du_kien)
  RETURNING id INTO v_chuyen_id;

  INSERT INTO public.chuyen_xe_chang(
    chuyen_xe_id,thu_tu_chuyen,kho_di_id,kho_den_id,
    nguoi_phan_cong_id,ngay_den_du_kien
  ) VALUES(
    v_chuyen_id,1,p_kho_di_id,p_kho_den_id,v_nv_id,p_ngay_du_kien
  );

  IF v_cap_di=2 THEN
    INSERT INTO public.chuyen_xe_chang(
      chuyen_xe_id,thu_tu_chuyen,kho_di_id,kho_den_id,
      nguoi_phan_cong_id,ngay_den_du_kien
    ) VALUES(
      v_chuyen_id,2,p_kho_den_id,p_kho_di_id,v_nv_id,NULL
    );
  END IF;

  RETURN v_chuyen_id;
END;
$$;

-- Bổ sung chặng về cho những chuyến cấp 2 -> cấp 1 được tạo trước bản vá này.
-- Chỉ tác động chuyến đang hoạt động và chưa có chặng thứ hai.
INSERT INTO public.chuyen_xe_chang(
  chuyen_xe_id,thu_tu_chuyen,kho_di_id,kho_den_id,
  nguoi_phan_cong_id,ngay_den_du_kien
)
SELECT cx.id,2,c1.kho_den_id,c1.kho_di_id,c1.nguoi_phan_cong_id,NULL
FROM public.chuyen_xe cx
JOIN public.chuyen_xe_chang c1
  ON c1.chuyen_xe_id=cx.id AND c1.thu_tu_chuyen=1
JOIN public.kho_hang k2
  ON k2.id=c1.kho_di_id
  AND k2.cap_kho=2
  AND k2.kho_trung_tam_id=c1.kho_den_id
WHERE cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
  AND NOT EXISTS(
    SELECT 1 FROM public.chuyen_xe_chang c2
    WHERE c2.chuyen_xe_id=cx.id AND c2.thu_tu_chuyen>1
  )
ON CONFLICT(chuyen_xe_id,thu_tu_chuyen) DO NOTHING;

-- Khôi phục các chuyến đã bị chuyển nhầm sang chặng về trước khi có nhật ký
-- quét nhập. Khi chưa có bất kỳ lần quét nhập nào tại chặng đến, toàn bộ kiện
-- vẫn thuộc chặng đi và chuyến phải ở trạng thái DA_DEN để tiếp tục dỡ hàng.
UPDATE public.chuyen_xe_chang c1
SET trang_thai='DA_DEN',ngay_cap_nhat=NOW()
WHERE c1.thu_tu_chuyen=1
  AND EXISTS(
    SELECT 1 FROM public.chuyen_xe cx
    WHERE cx.id=c1.chuyen_xe_id
      AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
  )
  AND EXISTS(
    SELECT 1 FROM public.niem_phong_xe np
    WHERE np.chuyen_xe_id=c1.chuyen_xe_id
      AND np.kho_niem_phong_id=c1.kho_di_id
      AND np.kho_mo_niem_phong_id=c1.kho_den_id
      AND np.trang_thai='DA_MO'
  )
  AND EXISTS(
    SELECT 1 FROM public.chi_tiet_chuyen_xe ct
    WHERE ct.chuyen_xe_id=c1.chuyen_xe_id
      AND NOT EXISTS(
        SELECT 1 FROM public.quet_nhap_kho_chang qn
        WHERE qn.chuyen_xe_chang_id=c1.id
          AND qn.don_hang_id=ct.don_hang_id
      )
  )
  AND NOT EXISTS(
    SELECT 1
    FROM public.chuyen_xe_chang c_sau
    JOIN public.niem_phong_xe np_sau
      ON np_sau.chuyen_xe_id=c_sau.chuyen_xe_id
      AND np_sau.kho_niem_phong_id=c_sau.kho_di_id
      AND np_sau.trang_thai='DA_NIEM_PHONG'
    WHERE c_sau.chuyen_xe_id=c1.chuyen_xe_id
      AND c_sau.thu_tu_chuyen>c1.thu_tu_chuyen
  );

WITH chuyen_can_sua AS (
  SELECT cx.id AS chuyen_xe_id,c1.id AS chang_den_id
  FROM public.chuyen_xe cx
  JOIN public.chuyen_xe_chang c1
    ON c1.chuyen_xe_id=cx.id AND c1.thu_tu_chuyen=1 AND c1.trang_thai='DA_DEN'
  JOIN public.chuyen_xe_chang c2
    ON c2.chuyen_xe_id=cx.id AND c2.thu_tu_chuyen=2 AND c2.trang_thai='CHO_KHOI_HANH'
  WHERE cx.trang_thai IN ('DA_DEN','DANG_XEP_HANG')
    AND NOT EXISTS(
      SELECT 1 FROM public.quet_nhap_kho_chang qn
      WHERE qn.chuyen_xe_chang_id=c1.id
    )
    AND NOT EXISTS(
      SELECT 1 FROM public.niem_phong_xe np
      WHERE np.chuyen_xe_id=cx.id
        AND np.kho_niem_phong_id=c2.kho_di_id
        AND np.trang_thai='DA_NIEM_PHONG'
    )
)
UPDATE public.chi_tiet_chuyen_xe ct
SET chuyen_xe_chang_id=s.chang_den_id,
    da_quet_nhap_kho=FALSE,
    trang_thai='DANG_VAN_CHUYEN',
    ngay_do_hang=NULL
FROM chuyen_can_sua s
WHERE ct.chuyen_xe_id=s.chuyen_xe_id;

UPDATE public.chuyen_xe cx
SET trang_thai='DA_DEN',ngay_cap_nhat=NOW()
WHERE cx.trang_thai='DANG_XEP_HANG'
  AND EXISTS(
    SELECT 1
    FROM public.chuyen_xe_chang c1
    JOIN public.chi_tiet_chuyen_xe ct ON ct.chuyen_xe_chang_id=c1.id
    WHERE c1.chuyen_xe_id=cx.id
      AND c1.thu_tu_chuyen=1
      AND c1.trang_thai='DA_DEN'
      AND NOT EXISTS(
        SELECT 1 FROM public.quet_nhap_kho_chang qn
        WHERE qn.chuyen_xe_chang_id=c1.id
          AND qn.don_hang_id=ct.don_hang_id
      )
  );

-- Cập nhật đúng từng chặng: đến kho cấp 1 xong mới được chạy chặng quay về cấp 2.
CREATE OR REPLACE FUNCTION public.cap_nhat_chuyen_xe_tai_xe(
  p_chuyen_xe_id BIGINT,
  p_trang_thai_moi TEXT
) RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=public
AS $$
DECLARE
  v_trang_thai VARCHAR(30);
  v_xe_id BIGINT;
  v_chang_id BIGINT;
  v_con_chang_cho BOOLEAN;
BEGIN
  SELECT cx.trang_thai,x.id
  INTO v_trang_thai,v_xe_id
  FROM public.chuyen_xe cx
  JOIN public.xe x ON x.id=cx.xe_id
  JOIN public.nhan_vien nv ON nv.id=x.tai_xe_id
  WHERE cx.id=p_chuyen_xe_id
    AND nv.auth_user_id=auth.uid()
    AND nv.vai_tro='VAN_CHUYEN'
    AND nv.trang_thai_duyet='DA_DUYET'
    AND nv.trang_thai='HOAT_DONG'
  FOR UPDATE OF cx,x;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy chuyến xe được phân công'; END IF;

  IF p_trang_thai_moi='DANG_DI' THEN
    IF v_trang_thai NOT IN ('CHO_KHOI_HANH','DANG_XEP_HANG','DA_DEN') THEN
      RAISE EXCEPTION 'Không thể bắt đầu chặng từ trạng thái %',v_trang_thai;
    END IF;
    SELECT c.id INTO v_chang_id
    FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=p_chuyen_xe_id
      AND c.trang_thai='CHO_KHOI_HANH'
    ORDER BY c.thu_tu_chuyen
    LIMIT 1
    FOR UPDATE;
    IF v_chang_id IS NULL THEN RAISE EXCEPTION 'Chuyến không còn chặng chờ khởi hành'; END IF;
    IF NOT EXISTS(
      SELECT 1
      FROM public.niem_phong_xe np
      JOIN public.chuyen_xe_chang c ON c.id=v_chang_id
      WHERE np.chuyen_xe_id=p_chuyen_xe_id
        AND np.kho_niem_phong_id=c.kho_di_id
        AND np.trang_thai='DA_NIEM_PHONG'
    ) THEN
      RAISE EXCEPTION 'Xe phải được kho khởi hành niêm phong trước khi chạy chặng này';
    END IF;

    UPDATE public.chuyen_xe_chang
    SET trang_thai='DANG_DI',
        ngay_khoi_hanh=COALESCE(ngay_khoi_hanh,NOW()),
        ngay_cap_nhat=NOW()
    WHERE id=v_chang_id;
    UPDATE public.chuyen_xe
    SET trang_thai='DANG_DI',
        ngay_khoi_hanh=COALESCE(ngay_khoi_hanh,NOW()),
        ngay_cap_nhat=NOW()
    WHERE id=p_chuyen_xe_id;
    UPDATE public.xe SET trang_thai='DANG_CHAY',ngay_cap_nhat=NOW()
    WHERE id=v_xe_id;
    UPDATE public.chi_tiet_chuyen_xe SET trang_thai='DANG_VAN_CHUYEN'
    WHERE chuyen_xe_id=p_chuyen_xe_id AND trang_thai='DA_XEP_HANG';

  ELSIF p_trang_thai_moi='DA_DEN' THEN
    IF v_trang_thai<>'DANG_DI' THEN
      RAISE EXCEPTION 'Không thể xác nhận đến kho từ trạng thái %',v_trang_thai;
    END IF;
    SELECT c.id INTO v_chang_id
    FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=p_chuyen_xe_id AND c.trang_thai='DANG_DI'
    ORDER BY c.thu_tu_chuyen
    LIMIT 1
    FOR UPDATE;
    IF v_chang_id IS NULL THEN RAISE EXCEPTION 'Không tìm thấy chặng đang di chuyển'; END IF;

    UPDATE public.chuyen_xe_chang
    SET trang_thai='DA_DEN',
        ngay_den_thuc_te=COALESCE(ngay_den_thuc_te,NOW()),
        ngay_cap_nhat=NOW()
    WHERE id=v_chang_id;
    SELECT EXISTS(
      SELECT 1 FROM public.chuyen_xe_chang c
      WHERE c.chuyen_xe_id=p_chuyen_xe_id AND c.trang_thai='CHO_KHOI_HANH'
    ) INTO v_con_chang_cho;
    UPDATE public.chuyen_xe
    SET trang_thai='DA_DEN',
        ngay_den_thuc_te=CASE WHEN v_con_chang_cho THEN ngay_den_thuc_te
          ELSE COALESCE(ngay_den_thuc_te,NOW()) END,
        ngay_cap_nhat=NOW()
    WHERE id=p_chuyen_xe_id;

  ELSIF p_trang_thai_moi='DA_HOAN_THANH' THEN
    IF v_trang_thai<>'DA_DEN' THEN
      RAISE EXCEPTION 'Không thể hoàn thành chuyến từ trạng thái %',v_trang_thai;
    END IF;
    IF EXISTS(
      SELECT 1 FROM public.chuyen_xe_chang c
      WHERE c.chuyen_xe_id=p_chuyen_xe_id AND c.trang_thai<>'DA_DEN'
    ) THEN
      RAISE EXCEPTION 'Xe còn chặng quay về chưa hoàn thành';
    END IF;
    IF EXISTS(SELECT 1 FROM public.niem_phong_xe np
      WHERE np.chuyen_xe_id=p_chuyen_xe_id AND np.trang_thai='DA_NIEM_PHONG') THEN
      RAISE EXCEPTION 'Kho đến phải mở niêm phong trước khi hoàn thành chuyến';
    END IF;
    IF EXISTS(SELECT 1 FROM public.chi_tiet_chuyen_xe ct
      WHERE ct.chuyen_xe_id=p_chuyen_xe_id AND ct.da_quet_nhap_kho=FALSE) THEN
      RAISE EXCEPTION 'Kho đến chưa dỡ hết kiện hàng';
    END IF;
    UPDATE public.chuyen_xe
    SET trang_thai='DA_HOAN_THANH',
        ngay_den_thuc_te=COALESCE(ngay_den_thuc_te,NOW()),
        ngay_cap_nhat=NOW()
    WHERE id=p_chuyen_xe_id;
    UPDATE public.xe SET trang_thai='SAN_SANG',ngay_cap_nhat=NOW()
    WHERE id=v_xe_id;
    UPDATE public.chi_tiet_chuyen_xe
    SET trang_thai='DA_DO_HANG',ngay_do_hang=COALESCE(ngay_do_hang,NOW())
    WHERE chuyen_xe_id=p_chuyen_xe_id;
  ELSE
    RAISE EXCEPTION 'Trạng thái chuyến không hợp lệ';
  END IF;
END;
$$;

