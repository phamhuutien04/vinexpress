-- Không cho một xe nhận đồng thời nhiều chuyến chưa kết thúc.
-- Chuyến xuất phát từ kho cấp 2 lên kho cấp 1 được tạo thêm chặng quay về kho cấp 2.
-- Chạy an toàn nhiều lần trong Supabase SQL Editor, không xóa dữ liệu hiện tại.

-- Ghi rõ kiện thuộc chặng nào để kiện lượt đi không bị nhầm sang lượt về.
ALTER TABLE public.chi_tiet_chuyen_xe
ADD COLUMN IF NOT EXISTS chuyen_xe_chang_id BIGINT
REFERENCES public.chuyen_xe_chang(id) ON UPDATE CASCADE ON DELETE SET NULL;

ALTER TABLE public.chi_tiet_chuyen_xe
ADD COLUMN IF NOT EXISTS da_quet_nhap_kho BOOLEAN NOT NULL DEFAULT FALSE;

CREATE INDEX IF NOT EXISTS idx_chi_tiet_chuyen_xe_chang
ON public.chi_tiet_chuyen_xe(chuyen_xe_chang_id);

-- Nhật ký này là bằng chứng duy nhất rằng kiện đã được nhân viên quét nhập
-- tại kho đến. Tháo niêm phong hoặc đổi trạng thái chuyến không tạo bản ghi này.
CREATE TABLE IF NOT EXISTS public.quet_nhap_kho_chang (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chuyen_xe_chang_id BIGINT NOT NULL
    REFERENCES public.chuyen_xe_chang(id) ON UPDATE CASCADE ON DELETE CASCADE,
  don_hang_id BIGINT NOT NULL
    REFERENCES public.don_hang(id) ON UPDATE CASCADE ON DELETE CASCADE,
  kho_hang_id BIGINT NOT NULL
    REFERENCES public.kho_hang(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  nhan_vien_id BIGINT
    REFERENCES public.nhan_vien(id) ON UPDATE CASCADE ON DELETE SET NULL,
  quet_luc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_quet_nhap_kho_chang UNIQUE(chuyen_xe_chang_id,don_hang_id)
);

CREATE INDEX IF NOT EXISTS idx_quet_nhap_kho_chang_don
ON public.quet_nhap_kho_chang(don_hang_id);

UPDATE public.chi_tiet_chuyen_xe ct
SET chuyen_xe_chang_id=c.id
FROM public.chuyen_xe_chang c
WHERE ct.chuyen_xe_chang_id IS NULL
  AND c.chuyen_xe_id=ct.chuyen_xe_id
  AND c.thu_tu_chuyen=1;

-- Chỉ các chuyến đã kết thúc từ trước mới được coi là đã nhập kho.
-- Chuyến đang DA_DEN phải quét thật tại kho đến, kể cả dữ liệu trạng thái cũ bị sai.
UPDATE public.chi_tiet_chuyen_xe ct
SET da_quet_nhap_kho=TRUE
FROM public.chuyen_xe cx
WHERE cx.id=ct.chuyen_xe_id
  AND cx.trang_thai='DA_HOAN_THANH'
  AND ct.trang_thai='DA_DO_HANG';

-- Sửa các chuyến từng bị chuyển nhầm sang DANG_XEP_HANG ngay sau khi tháo
-- niêm phong. Nếu chặng đến đã DA_DEN nhưng còn kiện chưa quét nhập thì xe
-- vẫn đang ở công đoạn dỡ hàng tại kho đến.
UPDATE public.chuyen_xe cx
SET trang_thai='DA_DEN',ngay_cap_nhat=NOW()
WHERE cx.trang_thai='DANG_XEP_HANG'
  AND EXISTS(
    SELECT 1
    FROM public.chuyen_xe_chang c
    JOIN public.chi_tiet_chuyen_xe ct
      ON ct.chuyen_xe_chang_id=c.id
    WHERE c.chuyen_xe_id=cx.id
      AND c.trang_thai='DA_DEN'
      AND ct.da_quet_nhap_kho=FALSE
  );

CREATE OR REPLACE FUNCTION public.kiem_tra_xe_chi_co_mot_chuyen_dang_hoat_dong()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path=public
AS $$
BEGIN
  IF NEW.trang_thai IN ('DA_HOAN_THANH','DA_HUY') THEN
    RETURN NEW;
  END IF;

  -- Chỉ kiểm tra khi tạo mới, đổi xe hoặc mở lại một chuyến đã kết thúc.
  -- Các lần cập nhật trạng thái bình thường của chính chuyến không bị chặn.
  IF TG_OP='UPDATE'
    AND NEW.xe_id=OLD.xe_id
    AND OLD.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY') THEN
    RETURN NEW;
  END IF;

  -- Khóa theo xe để hai yêu cầu gán xe chạy đồng thời không thể cùng thành công.
  PERFORM 1 FROM public.xe x WHERE x.id=NEW.xe_id FOR UPDATE;

  IF EXISTS(
    SELECT 1
    FROM public.chuyen_xe cx
    WHERE cx.xe_id=NEW.xe_id
      AND cx.id<>COALESCE(NEW.id,0)
      AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
  ) THEN
    RAISE EXCEPTION 'Xe đang có chuyến chưa hoàn thành, không thể gán thêm chuyến';
  END IF;

  RETURN NEW;
END;
$$;

-- Gắn trạng thái niêm phong vào đúng từng chặng để giao diện tài xế chỉ mở
-- nút khởi hành khi niêm phong được tạo tại kho đi của chặng đó.
CREATE OR REPLACE FUNCTION public.chuyen_xe_cua_tai_xe_co_chang()
RETURNS TABLE (
  id BIGINT,ma_chuyen VARCHAR,trang_thai VARCHAR,
  ngay_khoi_hanh TIMESTAMPTZ,ngay_du_kien TIMESTAMPTZ,ngay_den_thuc_te TIMESTAMPTZ,
  bien_so_xe VARCHAR,tai_trong NUMERIC,kho_di_ten VARCHAR,kho_den_ten VARCHAR,
  so_don_hang BIGINT,chang_duong JSONB,da_niem_phong BOOLEAN,ma_niem_phong VARCHAR
)
LANGUAGE plpgsql SECURITY DEFINER STABLE SET search_path=public AS $$
BEGIN
  IF NOT EXISTS(SELECT 1 FROM public.nhan_vien nv
    WHERE nv.auth_user_id=auth.uid() AND nv.vai_tro='VAN_CHUYEN'
      AND nv.trang_thai_duyet='DA_DUYET' AND nv.trang_thai='HOAT_DONG') THEN
    RAISE EXCEPTION 'Không có quyền xem chuyến xe';
  END IF;

  RETURN QUERY
  SELECT cx.id,cx.ma_chuyen::VARCHAR,cx.trang_thai::VARCHAR,
    cx.ngay_khoi_hanh,cx.ngay_du_kien,cx.ngay_den_thuc_te,
    x.bien_so_xe::VARCHAR,x.tai_trong,kd.ten_kho::VARCHAR,kden.ten_kho::VARCHAR,
    (SELECT COUNT(*) FROM public.chi_tiet_chuyen_xe ct
      WHERE ct.chuyen_xe_id=cx.id)::BIGINT,
    COALESCE(tuyen.chang_duong,'[]'::JSONB),
    (niem_phong.id IS NOT NULL),niem_phong.ma_niem_phong::VARCHAR
  FROM public.chuyen_xe cx
  JOIN public.xe x ON x.id=cx.xe_id
  JOIN public.nhan_vien nv ON nv.id=x.tai_xe_id
  LEFT JOIN LATERAL (SELECT c.kho_di_id FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=cx.id ORDER BY c.thu_tu_chuyen LIMIT 1) dau ON TRUE
  LEFT JOIN LATERAL (SELECT c.kho_den_id FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=cx.id ORDER BY c.thu_tu_chuyen DESC LIMIT 1) cuoi ON TRUE
  LEFT JOIN public.kho_hang kd ON kd.id=dau.kho_di_id
  LEFT JOIN public.kho_hang kden ON kden.id=cuoi.kho_den_id
  LEFT JOIN LATERAL (
    SELECT jsonb_agg(jsonb_build_object(
      'id',c.id,'thu_tu_chuyen',c.thu_tu_chuyen,'trang_thai',c.trang_thai,
      'ngay_khoi_hanh',c.ngay_khoi_hanh,'ngay_den_du_kien',c.ngay_den_du_kien,
      'ngay_den_thuc_te',c.ngay_den_thuc_te,
      'kho_di_id',kdi.id,'kho_di_ma',kdi.ma_kho,'kho_di_ten',kdi.ten_kho,
      'kho_di_dia_chi',kdi.dia_chi,'kho_di_so_dien_thoai',kdi.so_dien_thoai,
      'kho_den_id',kde.id,'kho_den_ma',kde.ma_kho,'kho_den_ten',kde.ten_kho,
      'kho_den_dia_chi',kde.dia_chi,'kho_den_so_dien_thoai',kde.so_dien_thoai,
      'da_niem_phong',COALESCE(niem_phong_chang.da_niem_phong,FALSE)
    ) ORDER BY c.thu_tu_chuyen) AS chang_duong
    FROM public.chuyen_xe_chang c
    JOIN public.kho_hang kdi ON kdi.id=c.kho_di_id
    JOIN public.kho_hang kde ON kde.id=c.kho_den_id
    LEFT JOIN LATERAL (
      SELECT TRUE AS da_niem_phong
      FROM public.niem_phong_xe np
      WHERE np.chuyen_xe_id=cx.id
        AND np.kho_niem_phong_id=c.kho_di_id
        AND np.trang_thai='DA_NIEM_PHONG'
      LIMIT 1
    ) niem_phong_chang ON TRUE
    WHERE c.chuyen_xe_id=cx.id
  ) tuyen ON TRUE
  LEFT JOIN LATERAL (SELECT np.id,np.ma_niem_phong FROM public.niem_phong_xe np
    WHERE np.chuyen_xe_id=cx.id AND np.trang_thai='DA_NIEM_PHONG'
    ORDER BY np.thoi_gian_niem_phong DESC LIMIT 1) niem_phong ON TRUE
  WHERE nv.auth_user_id=auth.uid()
  ORDER BY CASE cx.trang_thai WHEN 'DANG_DI' THEN 1 WHEN 'DANG_XEP_HANG' THEN 2
    WHEN 'CHO_KHOI_HANH' THEN 3 WHEN 'DA_DEN' THEN 4 ELSE 5 END,cx.ngay_tao DESC;
END;
$$;

-- Trả đúng thao tác của chặng hiện tại tại kho: dỡ xong chặng đến mới chuyển
-- sang xếp hàng cho chặng kế tiếp. Mỗi lần chỉ trả một chặng của một chuyến.
CREATE OR REPLACE FUNCTION public.nhan_vien_kho_tim_chuyen_theo_xe(
  p_tu_khoa TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path=public
AS $$
DECLARE
  v_kho_id BIGINT;
  v_xe public.xe%ROWTYPE;
  v_tu_khoa TEXT := BTRIM(COALESCE(p_tu_khoa,''));
  v_bien_so_chuan TEXT;
  v_chuyen_xe JSONB;
BEGIN
  SELECT nv.kho_hang_id INTO v_kho_id
  FROM public.nhan_vien nv
  WHERE nv.auth_user_id=auth.uid()
    AND nv.vai_tro='NHAN_VIEN_KHO'
    AND nv.trang_thai_duyet='DA_DUYET'
    AND nv.trang_thai='HOAT_DONG';
  IF v_kho_id IS NULL THEN RAISE EXCEPTION 'Nhân viên chưa được gán kho'; END IF;
  IF v_tu_khoa='' THEN RAISE EXCEPTION 'Hãy nhập ID xe hoặc biển số xe'; END IF;

  v_bien_so_chuan := regexp_replace(UPPER(v_tu_khoa),'[^A-Z0-9]','','g');
  SELECT x.* INTO v_xe
  FROM public.xe x
  LEFT JOIN public.nhan_vien tx ON tx.id=x.tai_xe_id
  WHERE (
      (v_tu_khoa ~ '^[0-9]+$' AND x.id::TEXT=v_tu_khoa)
      OR regexp_replace(UPPER(x.bien_so_xe),'[^A-Z0-9]','','g')=v_bien_so_chuan
    )
    AND (
      tx.kho_hang_id=v_kho_id
      OR EXISTS(
        SELECT 1 FROM public.chuyen_xe cx
        JOIN public.chuyen_xe_chang c ON c.chuyen_xe_id=cx.id
        WHERE cx.xe_id=x.id
          AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
          AND (c.kho_di_id=v_kho_id OR c.kho_den_id=v_kho_id)
      )
    )
  ORDER BY CASE WHEN x.id::TEXT=v_tu_khoa THEN 0 ELSE 1 END
  LIMIT 1;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Không tìm thấy xe trong phạm vi kho với ID hoặc biển số đã nhập';
  END IF;

  SELECT COALESCE(jsonb_agg(to_jsonb(q)-'ngay_tao' ORDER BY q.ngay_tao DESC),'[]'::JSONB)
  INTO v_chuyen_xe
  FROM (
    SELECT cx.id,cx.ma_chuyen::VARCHAR,cx.trang_thai::VARCHAR,
      x.bien_so_xe::VARCHAR,tx.ho_ten::VARCHAR AS ten_tai_xe,
      c.id AS chang_id,c.thu_tu_chuyen,c.kho_di_id,
      kd.ten_kho::VARCHAR AS ten_kho_di,c.kho_den_id,
      kn.ten_kho::VARCHAR AS ten_kho_den,
      CASE WHEN c.kho_di_id=v_kho_id THEN 'XEP_LEN_XE' ELSE 'NHAP_KHO' END AS thao_tac,
      EXISTS(
        SELECT 1 FROM public.niem_phong_xe np
        WHERE np.chuyen_xe_id=cx.id AND np.trang_thai='DA_NIEM_PHONG'
      ) AS da_niem_phong,
      (SELECT np.ma_niem_phong FROM public.niem_phong_xe np
        WHERE np.chuyen_xe_id=cx.id AND np.trang_thai='DA_NIEM_PHONG'
        ORDER BY np.thoi_gian_niem_phong DESC LIMIT 1) AS ma_niem_phong,
      (SELECT COUNT(*) FROM public.chi_tiet_chuyen_xe ct
        WHERE ct.chuyen_xe_id=cx.id)::BIGINT AS so_kien,
      cx.ngay_tao
    FROM public.chuyen_xe cx
    JOIN public.xe x ON x.id=cx.xe_id
    LEFT JOIN public.nhan_vien tx ON tx.id=x.tai_xe_id
    JOIN LATERAL (
      SELECT c0.*
      FROM public.chuyen_xe_chang c0
      LEFT JOIN LATERAL (
        SELECT 1 AS tim_thay
        FROM public.niem_phong_xe np0
        WHERE np0.chuyen_xe_id=cx.id
          AND np0.kho_niem_phong_id=c0.kho_di_id
          AND np0.trang_thai='DA_NIEM_PHONG'
        LIMIT 1
      ) niem_phong_chang ON TRUE
      LEFT JOIN LATERAL (
        SELECT 1 AS tim_thay
        FROM public.chi_tiet_chuyen_xe ct0
        WHERE ct0.chuyen_xe_id=cx.id
          AND NOT EXISTS(
            SELECT 1 FROM public.quet_nhap_kho_chang qn0
            WHERE qn0.chuyen_xe_chang_id=c0.id
              AND qn0.don_hang_id=ct0.don_hang_id
          )
        LIMIT 1
      ) kien_chua_do ON TRUE
      WHERE c0.chuyen_xe_id=cx.id
        AND (
          (
            c0.kho_den_id=v_kho_id
            AND c0.trang_thai IN ('DANG_DI','DA_DEN')
            AND (
              c0.trang_thai='DANG_DI'
              OR cx.trang_thai='DA_DEN'
              OR niem_phong_chang.tim_thay IS NOT NULL
              OR kien_chua_do.tim_thay IS NOT NULL
            )
          )
          OR (
            c0.kho_di_id=v_kho_id
            AND c0.trang_thai='CHO_KHOI_HANH'
            AND cx.trang_thai IN ('CHO_KHOI_HANH','DANG_XEP_HANG')
            AND NOT EXISTS(
              SELECT 1 FROM public.chuyen_xe_chang truoc
              WHERE truoc.chuyen_xe_id=cx.id
                AND truoc.thu_tu_chuyen<c0.thu_tu_chuyen
                AND truoc.trang_thai<>'DA_DEN'
            )
            AND NOT EXISTS(
              SELECT 1
              FROM public.chuyen_xe_chang truoc
              JOIN public.chi_tiet_chuyen_xe ct_truoc
                ON ct_truoc.chuyen_xe_id=truoc.chuyen_xe_id
              WHERE truoc.chuyen_xe_id=c0.chuyen_xe_id
                AND truoc.thu_tu_chuyen<c0.thu_tu_chuyen
                AND NOT EXISTS(
                  SELECT 1 FROM public.quet_nhap_kho_chang qn_truoc
                  WHERE qn_truoc.chuyen_xe_chang_id=truoc.id
                    AND qn_truoc.don_hang_id=ct_truoc.don_hang_id
                )
            )
          )
        )
      ORDER BY CASE WHEN c0.kho_den_id=v_kho_id THEN 0 ELSE 1 END,
        c0.thu_tu_chuyen
      LIMIT 1
    ) c ON TRUE
    JOIN public.kho_hang kd ON kd.id=c.kho_di_id
    JOIN public.kho_hang kn ON kn.id=c.kho_den_id
    WHERE cx.xe_id=v_xe.id
      AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')
  ) q;

  RETURN jsonb_build_object(
    'xe',jsonb_build_object(
      'id',v_xe.id,'bien_so_xe',v_xe.bien_so_xe,
      'trang_thai',v_xe.trang_thai,
      'ten_tai_xe',(SELECT nv.ho_ten FROM public.nhan_vien nv WHERE nv.id=v_xe.tai_xe_id)
    ),
    'chuyen_xe',v_chuyen_xe
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.nhan_vien_kho_quet_kien_chuyen(
  p_chuyen_xe_id BIGINT,p_ma TEXT,p_thao_tac TEXT
) RETURNS VARCHAR
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_nv public.nhan_vien%ROWTYPE;
  v_don public.don_hang%ROWTYPE;
  v_chang public.chuyen_xe_chang%ROWTYPE;
  v_thao_tac TEXT := UPPER(BTRIM(COALESCE(p_thao_tac,'')));
  v_trang_thai VARCHAR;
BEGIN
  SELECT nv.* INTO v_nv FROM public.nhan_vien nv
  WHERE nv.auth_user_id=auth.uid() AND nv.vai_tro='NHAN_VIEN_KHO'
    AND nv.trang_thai_duyet='DA_DUYET' AND nv.trang_thai='HOAT_DONG';
  IF NOT FOUND OR v_nv.kho_hang_id IS NULL THEN RAISE EXCEPTION 'Nhân viên chưa được gán kho'; END IF;

  IF v_thao_tac='XEP_LEN_XE' THEN
    SELECT c.* INTO v_chang FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=p_chuyen_xe_id
      AND c.kho_di_id=v_nv.kho_hang_id
      AND c.trang_thai='CHO_KHOI_HANH'
      AND NOT EXISTS(SELECT 1 FROM public.chuyen_xe_chang truoc
        WHERE truoc.chuyen_xe_id=c.chuyen_xe_id
          AND truoc.thu_tu_chuyen<c.thu_tu_chuyen
          AND truoc.trang_thai<>'DA_DEN')
    ORDER BY c.thu_tu_chuyen LIMIT 1;
  ELSIF v_thao_tac='NHAP_KHO' THEN
    SELECT c.* INTO v_chang FROM public.chuyen_xe_chang c
    WHERE c.chuyen_xe_id=p_chuyen_xe_id
      AND c.kho_den_id=v_nv.kho_hang_id
      AND c.trang_thai='DA_DEN'
    ORDER BY c.thu_tu_chuyen DESC LIMIT 1;
  ELSE
    RAISE EXCEPTION 'Thao tác quét không hợp lệ';
  END IF;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy chặng phù hợp tại kho của bạn'; END IF;

  SELECT dh.* INTO v_don FROM public.don_hang dh
  WHERE dh.ma_qr::TEXT=BTRIM(p_ma) OR UPPER(dh.ma_van_don)=UPPER(BTRIM(p_ma))
  FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy kiện hàng'; END IF;

  IF v_thao_tac='XEP_LEN_XE' THEN
    IF EXISTS(SELECT 1 FROM public.niem_phong_xe np
      WHERE np.chuyen_xe_id=p_chuyen_xe_id AND np.trang_thai='DA_NIEM_PHONG') THEN
      RAISE EXCEPTION 'Xe đã niêm phong, không thể xếp thêm kiện';
    END IF;
    IF v_don.kho_hien_tai_id IS DISTINCT FROM v_nv.kho_hang_id THEN
      RAISE EXCEPTION 'Kiện hàng chưa có trong kho này';
    END IF;
    IF EXISTS(SELECT 1 FROM public.chi_tiet_chuyen_xe ct
      JOIN public.chuyen_xe cx ON cx.id=ct.chuyen_xe_id
      WHERE ct.don_hang_id=v_don.id AND cx.id<>p_chuyen_xe_id
        AND cx.trang_thai NOT IN ('DA_HOAN_THANH','DA_HUY')) THEN
      RAISE EXCEPTION 'Kiện hàng đã thuộc chuyến xe khác';
    END IF;
    INSERT INTO public.chi_tiet_chuyen_xe(
      chuyen_xe_id,don_hang_id,chuyen_xe_chang_id,trang_thai
    )
    VALUES(p_chuyen_xe_id,v_don.id,v_chang.id,'DA_XEP_HANG')
    ON CONFLICT(chuyen_xe_id,don_hang_id) DO UPDATE
      SET chuyen_xe_chang_id=EXCLUDED.chuyen_xe_chang_id,
          da_quet_nhap_kho=FALSE,trang_thai='DA_XEP_HANG',
          ngay_xep_hang=NOW(),ngay_do_hang=NULL;
    UPDATE public.chuyen_xe SET trang_thai='DANG_XEP_HANG',ngay_cap_nhat=NOW()
    WHERE id=p_chuyen_xe_id AND trang_thai IN ('CHO_KHOI_HANH','DA_DEN');
    v_trang_thai := 'DA_XEP_HANG';
  ELSE
    IF EXISTS(SELECT 1 FROM public.niem_phong_xe np
      WHERE np.chuyen_xe_id=p_chuyen_xe_id AND np.trang_thai='DA_NIEM_PHONG') THEN
      RAISE EXCEPTION 'Hãy mở niêm phong xe trước khi quét dỡ kiện';
    END IF;
    IF NOT EXISTS(SELECT 1 FROM public.chi_tiet_chuyen_xe ct
      WHERE ct.chuyen_xe_id=p_chuyen_xe_id
        AND ct.don_hang_id=v_don.id) THEN
      RAISE EXCEPTION 'Kiện hàng không thuộc chặng đang vận chuyển của xe này';
    END IF;
    IF EXISTS(
      SELECT 1 FROM public.quet_nhap_kho_chang qn
      WHERE qn.chuyen_xe_chang_id=v_chang.id
        AND qn.don_hang_id=v_don.id
    ) THEN
      RAISE EXCEPTION 'Kiện hàng đã được nhập vào kho này';
    END IF;
    UPDATE public.chi_tiet_chuyen_xe
    SET chuyen_xe_chang_id=v_chang.id,
        trang_thai='DA_DO_HANG',da_quet_nhap_kho=TRUE,ngay_do_hang=NOW()
    WHERE chuyen_xe_id=p_chuyen_xe_id
      AND don_hang_id=v_don.id;
    INSERT INTO public.quet_nhap_kho_chang(
      chuyen_xe_chang_id,don_hang_id,kho_hang_id,nhan_vien_id,quet_luc
    ) VALUES(v_chang.id,v_don.id,v_nv.kho_hang_id,v_nv.id,NOW())
    ON CONFLICT(chuyen_xe_chang_id,don_hang_id) DO NOTHING;
    UPDATE public.don_hang SET kho_hien_tai_id=v_nv.kho_hang_id,
      nhan_vien_hien_tai_id=v_nv.id,
      trang_thai=CASE WHEN kho_dich_id=v_nv.kho_hang_id
        THEN 'DEN_KHO_DICH' ELSE 'DEN_KHO_TRUNG_CHUYEN' END,
      ngay_cap_nhat=NOW() WHERE id=v_don.id;

    -- Chỉ mở công đoạn xếp chặng kế tiếp sau lần quét nhập cuối cùng.
    IF NOT EXISTS(
      SELECT 1 FROM public.chi_tiet_chuyen_xe ct
      WHERE ct.chuyen_xe_id=p_chuyen_xe_id
        AND NOT EXISTS(
          SELECT 1 FROM public.quet_nhap_kho_chang qn
          WHERE qn.chuyen_xe_chang_id=v_chang.id
            AND qn.don_hang_id=ct.don_hang_id
        )
    ) AND EXISTS(
      SELECT 1 FROM public.chuyen_xe_chang c_sau
      WHERE c_sau.chuyen_xe_id=p_chuyen_xe_id
        AND c_sau.thu_tu_chuyen>v_chang.thu_tu_chuyen
        AND c_sau.trang_thai='CHO_KHOI_HANH'
    ) THEN
      UPDATE public.chuyen_xe
      SET trang_thai='DANG_XEP_HANG',ngay_cap_nhat=NOW()
      WHERE id=p_chuyen_xe_id;
    END IF;
    v_trang_thai := 'DA_NHAP_KHO';
  END IF;
  RETURN v_trang_thai;
END;
$$;

CREATE OR REPLACE FUNCTION public.nhan_vien_kho_niem_phong_chuyen(
  p_chuyen_xe_id BIGINT,p_ma_niem_phong TEXT
) RETURNS VARCHAR
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_nv public.nhan_vien%ROWTYPE;
  v_chuyen public.chuyen_xe%ROWTYPE;
  v_chang public.chuyen_xe_chang%ROWTYPE;
  v_ma TEXT := UPPER(BTRIM(COALESCE(p_ma_niem_phong,'')));
  v_so_kien BIGINT;
BEGIN
  SELECT nv.* INTO v_nv FROM public.nhan_vien nv
  WHERE nv.auth_user_id=auth.uid() AND nv.vai_tro='NHAN_VIEN_KHO'
    AND nv.trang_thai_duyet='DA_DUYET' AND nv.trang_thai='HOAT_DONG';
  IF NOT FOUND OR v_nv.kho_hang_id IS NULL THEN RAISE EXCEPTION 'Nhân viên chưa được gán kho'; END IF;
  IF v_ma='' THEN RAISE EXCEPTION 'Hãy nhập mã niêm phong'; END IF;

  SELECT cx.* INTO v_chuyen FROM public.chuyen_xe cx
  WHERE cx.id=p_chuyen_xe_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy chuyến xe'; END IF;
  SELECT c.* INTO v_chang FROM public.chuyen_xe_chang c
  WHERE c.chuyen_xe_id=p_chuyen_xe_id
    AND c.kho_di_id=v_nv.kho_hang_id
    AND c.trang_thai='CHO_KHOI_HANH'
    AND NOT EXISTS(SELECT 1 FROM public.chuyen_xe_chang truoc
      WHERE truoc.chuyen_xe_id=c.chuyen_xe_id
        AND truoc.thu_tu_chuyen<c.thu_tu_chuyen
        AND truoc.trang_thai<>'DA_DEN')
  ORDER BY c.thu_tu_chuyen LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không có chặng chờ khởi hành từ kho của bạn'; END IF;
  IF v_chuyen.trang_thai NOT IN ('CHO_KHOI_HANH','DANG_XEP_HANG','DA_DEN') THEN
    RAISE EXCEPTION 'Trạng thái chuyến không cho phép niêm phong';
  END IF;
  IF EXISTS(SELECT 1 FROM public.niem_phong_xe np
    WHERE np.chuyen_xe_id=p_chuyen_xe_id AND np.trang_thai='DA_NIEM_PHONG') THEN
    RAISE EXCEPTION 'Xe đã được niêm phong';
  END IF;
  IF EXISTS(SELECT 1 FROM public.niem_phong_xe np
    WHERE UPPER(BTRIM(np.ma_niem_phong))=v_ma) THEN
    RAISE EXCEPTION 'Mã niêm phong đã được sử dụng';
  END IF;
  IF v_chang.thu_tu_chuyen>1 THEN
    IF EXISTS(
      SELECT 1 FROM public.chi_tiet_chuyen_xe ct
      WHERE ct.chuyen_xe_id=p_chuyen_xe_id
        AND EXISTS(
          SELECT 1 FROM public.chuyen_xe_chang truoc
          WHERE truoc.chuyen_xe_id=p_chuyen_xe_id
            AND truoc.thu_tu_chuyen<v_chang.thu_tu_chuyen
            AND NOT EXISTS(
              SELECT 1 FROM public.quet_nhap_kho_chang qn
              WHERE qn.chuyen_xe_chang_id=truoc.id
                AND qn.don_hang_id=ct.don_hang_id
            )
        )
    ) THEN
      RAISE EXCEPTION 'Phải dỡ hết kiện của chặng trước trước khi niêm phong chặng về';
    END IF;
  END IF;

  SELECT COUNT(*) INTO v_so_kien FROM public.chi_tiet_chuyen_xe ct
  WHERE ct.chuyen_xe_id=p_chuyen_xe_id
    AND ct.chuyen_xe_chang_id=v_chang.id
    AND ct.trang_thai='DA_XEP_HANG';
  IF v_so_kien=0 AND v_chang.thu_tu_chuyen=1 THEN
    RAISE EXCEPTION 'Chuyến chưa có kiện hàng để niêm phong';
  END IF;

  BEGIN
    INSERT INTO public.niem_phong_xe(
      chuyen_xe_id,ma_niem_phong,kho_niem_phong_id,nguoi_niem_phong_id,trang_thai
    ) VALUES(p_chuyen_xe_id,v_ma,v_nv.kho_hang_id,v_nv.id,'DA_NIEM_PHONG');
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'Mã niêm phong đã được sử dụng';
  END;
  RETURN v_ma;
END;
$$;

CREATE OR REPLACE FUNCTION public.nhan_vien_kho_mo_niem_phong_chuyen(
  p_chuyen_xe_id BIGINT,p_ma_niem_phong TEXT
) RETURNS VARCHAR
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_nv public.nhan_vien%ROWTYPE;
  v_chang public.chuyen_xe_chang%ROWTYPE;
  v_niem_phong public.niem_phong_xe%ROWTYPE;
  v_ma TEXT := UPPER(BTRIM(COALESCE(p_ma_niem_phong,'')));
BEGIN
  SELECT nv.* INTO v_nv FROM public.nhan_vien nv
  WHERE nv.auth_user_id=auth.uid() AND nv.vai_tro='NHAN_VIEN_KHO'
    AND nv.trang_thai_duyet='DA_DUYET' AND nv.trang_thai='HOAT_DONG';
  IF NOT FOUND OR v_nv.kho_hang_id IS NULL THEN RAISE EXCEPTION 'Nhân viên chưa được gán kho'; END IF;
  IF v_ma='' THEN RAISE EXCEPTION 'Hãy nhập mã niêm phong trên xe'; END IF;

  SELECT c.* INTO v_chang FROM public.chuyen_xe_chang c
  WHERE c.chuyen_xe_id=p_chuyen_xe_id
    AND c.kho_den_id=v_nv.kho_hang_id
    AND c.trang_thai='DA_DEN'
  ORDER BY c.thu_tu_chuyen DESC LIMIT 1;
  IF NOT FOUND THEN RAISE EXCEPTION 'Tài xế chưa xác nhận đến kho của bạn'; END IF;

  SELECT np.* INTO v_niem_phong FROM public.niem_phong_xe np
  WHERE np.chuyen_xe_id=p_chuyen_xe_id
    AND np.kho_niem_phong_id=v_chang.kho_di_id
    AND np.trang_thai='DA_NIEM_PHONG'
  ORDER BY np.thoi_gian_niem_phong DESC LIMIT 1 FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Không tìm thấy niêm phong đang đóng của chặng này'; END IF;
  IF UPPER(BTRIM(v_niem_phong.ma_niem_phong))<>v_ma THEN
    RAISE EXCEPTION 'Mã niêm phong không khớp với mã đã ghi nhận';
  END IF;
  UPDATE public.niem_phong_xe SET trang_thai='DA_MO',
    kho_mo_niem_phong_id=v_nv.kho_hang_id,nguoi_mo_id=v_nv.id,thoi_gian_mo=NOW()
  WHERE id=v_niem_phong.id;

  -- Mở niêm phong chỉ bắt đầu công đoạn dỡ xe. Không được tự chuyển sang
  -- chặng quay về trước khi từng kiện có nhật ký quét nhập tại kho đến.
  UPDATE public.chuyen_xe_chang
  SET trang_thai='DA_DEN',ngay_cap_nhat=NOW()
  WHERE id=v_chang.id;
  UPDATE public.chuyen_xe
  SET trang_thai='DA_DEN',ngay_cap_nhat=NOW()
  WHERE id=p_chuyen_xe_id;
  UPDATE public.chi_tiet_chuyen_xe ct
  SET chuyen_xe_chang_id=v_chang.id,
      da_quet_nhap_kho=FALSE,
      trang_thai='DANG_VAN_CHUYEN',
      ngay_do_hang=NULL
  WHERE ct.chuyen_xe_id=p_chuyen_xe_id
    AND NOT EXISTS(
      SELECT 1 FROM public.quet_nhap_kho_chang qn
      WHERE qn.chuyen_xe_chang_id=v_chang.id
        AND qn.don_hang_id=ct.don_hang_id
    );

  -- Tương thích chuyến cũ chỉ có một chặng: khi xe cấp 2 đã lên đúng
  -- kho cấp 1, gắn ngay chặng quay về kho cấp 2 sau khi mở niêm phong.
  IF v_chang.thu_tu_chuyen=1 THEN
    IF EXISTS(
      SELECT 1 FROM public.kho_hang k2
      WHERE k2.id=v_chang.kho_di_id
        AND k2.cap_kho=2
        AND k2.kho_trung_tam_id=v_chang.kho_den_id
    ) THEN
      IF NOT EXISTS(
        SELECT 1 FROM public.chuyen_xe_chang c2
        WHERE c2.chuyen_xe_id=p_chuyen_xe_id AND c2.thu_tu_chuyen>1
      ) THEN
        INSERT INTO public.chuyen_xe_chang(
          chuyen_xe_id,thu_tu_chuyen,kho_di_id,kho_den_id,
          nguoi_phan_cong_id,ngay_den_du_kien
        ) VALUES(
          p_chuyen_xe_id,2,v_chang.kho_den_id,v_chang.kho_di_id,
          v_chang.nguoi_phan_cong_id,NULL
        ) ON CONFLICT(chuyen_xe_id,thu_tu_chuyen) DO NOTHING;
      END IF;
    END IF;
  END IF;

  RETURN v_niem_phong.ma_niem_phong;
END;
$$;

