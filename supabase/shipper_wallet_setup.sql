-- ============================================================
-- DỮ LIỆU MẪU
-- Gán cho shipper đầu tiên (ID nhỏ nhất) và không tạo trùng khi chạy lại.
-- ============================================================
DO $$
DECLARE
    v_nhan_vien_id BIGINT;
    v_so_du_moi NUMERIC;
BEGIN
    SELECT nv.id INTO v_nhan_vien_id
    FROM public.nhan_vien nv
    WHERE nv.vai_tro = 'SHIPPER'
    ORDER BY nv.id
    LIMIT 1;

    IF v_nhan_vien_id IS NULL THEN
        RAISE NOTICE 'Chưa có shipper, bỏ qua dữ liệu ví mẫu';
        RETURN;
    END IF;

    INSERT INTO public.vi_shipper(nhan_vien_id, so_du)
    VALUES (v_nhan_vien_id, 0)
    ON CONFLICT (nhan_vien_id) DO NOTHING;

    IF NOT EXISTS (
        SELECT 1
        FROM public.giao_dich_vi_shipper gd
        WHERE gd.nhan_vien_id = v_nhan_vien_id
          AND gd.loai = 'NAP_TIEN'
          AND gd.noi_dung = 'Dữ liệu mẫu: số dư khởi tạo ví shipper'
    ) THEN
        UPDATE public.vi_shipper
        SET so_du = so_du + 200000,
            ngay_cap_nhat = NOW()
        WHERE nhan_vien_id = v_nhan_vien_id
        RETURNING so_du INTO v_so_du_moi;

        INSERT INTO public.giao_dich_vi_shipper(
            nhan_vien_id,
            loai,
            so_tien,
            so_du_sau,
            noi_dung
        ) VALUES (
            v_nhan_vien_id,
            'NAP_TIEN',
            200000,
            v_so_du_moi,
            'Dữ liệu mẫu: số dư khởi tạo ví shipper'
        );
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM public.yeu_cau_nap_vi_shipper yc
        WHERE yc.nhan_vien_id = v_nhan_vien_id
          AND yc.phuong_thuc = 'CHUYEN_KHOAN_MAU'
    ) THEN
        INSERT INTO public.yeu_cau_nap_vi_shipper(
            nhan_vien_id,
            so_tien,
            phuong_thuc,
            trang_thai
        ) VALUES (
            v_nhan_vien_id,
            100000,
            'CHUYEN_KHOAN_MAU',
            'CHO_DUYET'
        );
    END IF;
END;
$$;

