CREATE OR REPLACE FUNCTION public.bo_dau_lower(p_text TEXT)
RETURNS TEXT LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT regexp_replace(
    regexp_replace(
      regexp_replace(
        regexp_replace(
          regexp_replace(
            regexp_replace(
              regexp_replace(lower(COALESCE(p_text,'')),
                '[áàảãạăắằẳẵặâấầẩẫậ]', 'a', 'g'),
              '[éèẻẽẹêếềểễệ]', 'e', 'g'),
            '[íìỉĩị]', 'i', 'g'),
          '[óòỏõọôốồổỗộơớờởỡợ]', 'o', 'g'),
        '[úùủũụưứừửữự]', 'u', 'g'),
      '[ýỳỷỹỵ]', 'y', 'g'),
    'đ', 'd', 'g')
$$;

