CREATE OR REPLACE FUNCTION public.luu_dia_ban_giao_nhan(
  p_khu_vuc_id BIGINT, p_ten_dia_ban TEXT
) RETURNS BIGINT LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE
  v_id BIGINT;
  v_phuong_xa TEXT;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.nhan_vien nv
