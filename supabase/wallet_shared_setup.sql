    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vi_id BIGINT NOT NULL REFERENCES public.vi(id) ON DELETE CASCADE,
    so_tien NUMERIC(14,2) NOT NULL CHECK (so_tien >= 50000),
    ngan_hang VARCHAR(100) NOT NULL,
    so_tai_khoan VARCHAR(50) NOT NULL,
    chu_tai_khoan VARCHAR(150) NOT NULL,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_DUYET'
        CHECK (trang_thai IN ('CHO_DUYET', 'DA_DUYET', 'TU_CHOI')),
    ly_do_tu_choi TEXT,
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_xu_ly TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS public.yeu_cau_nap_rut_vi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vi_id BIGINT NOT NULL REFERENCES public.vi(id) ON DELETE CASCADE,
    loai VARCHAR(20) NOT NULL CHECK (loai IN ('NAP_TIEN', 'RUT_TIEN')),
    so_tien NUMERIC(14,2) NOT NULL CHECK (so_tien > 0),
    phuong_thuc VARCHAR(30),
    ngan_hang VARCHAR(100),
    so_tai_khoan VARCHAR(50),
    chu_tai_khoan VARCHAR(150),
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_DUYET'
