        'NAP_TIEN', 'RUT_TIEN', 'YEU_CAU_RUT', 'HOAN_RUT',
        'TRU_COD', 'NHAN_COD', 'HOAN_COD',
        'THU_NHAP_GIAO_HANG', 'DIEU_CHINH'
