DROP FUNCTION IF EXISTS public.tao_yeu_cau_rut_vi(NUMERIC, TEXT, TEXT, TEXT);
DROP FUNCTION IF EXISTS public.tao_yeu_cau_rut_vi(NUMERIC);
CREATE OR REPLACE FUNCTION public.tao_yeu_cau_rut_vi(
    p_so_tien NUMERIC
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_vi_id BIGINT;
    v_so_du NUMERIC;
    v_yeu_cau_id BIGINT;
    v_ngan_hang public.tai_khoan_ngan_hang_vi%ROWTYPE;
BEGIN
    IF p_so_tien < 50000 THEN
        RAISE EXCEPTION 'Số tiền rút tối thiểu là 50.000đ';
    END IF;
    PERFORM public.thong_tin_vi();
    SELECT v.id, v.so_du INTO v_vi_id, v_so_du
    FROM public.vi v
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid()
    FOR UPDATE OF v;

    IF v_vi_id IS NULL OR v_so_du < p_so_tien THEN
        RAISE EXCEPTION 'Số dư ví không đủ để rút %đ', ROUND(p_so_tien);
    END IF;

    SELECT * INTO v_ngan_hang
    FROM public.tai_khoan_ngan_hang_vi
    WHERE vi_id = v_vi_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Vui lòng liên kết tài khoản ngân hàng trước khi rút tiền';
    END IF;

    INSERT INTO public.yeu_cau_nap_rut_vi(
        vi_id, loai, so_tien, ngan_hang, so_tai_khoan, chu_tai_khoan
    ) VALUES (
        v_vi_id, 'RUT_TIEN', p_so_tien, v_ngan_hang.ngan_hang,
        v_ngan_hang.so_tai_khoan, v_ngan_hang.chu_tai_khoan
    ) RETURNING id INTO v_yeu_cau_id;

    UPDATE public.vi
    SET so_du = so_du - p_so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_vi_id RETURNING so_du INTO v_so_du;

    INSERT INTO public.giao_dich_vi(
        vi_id, yeu_cau_nap_rut_id, loai, so_tien, so_du_sau, noi_dung
    ) VALUES (
        v_vi_id, v_yeu_cau_id, 'YEU_CAU_RUT', p_so_tien, v_so_du,
        'Tạm giữ tiền cho yêu cầu rút #' || v_yeu_cau_id
    );
    RETURN v_yeu_cau_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.duyet_yeu_cau_rut_vi(p_yeu_cau_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_yeu_cau public.yeu_cau_nap_rut_vi%ROWTYPE;
BEGIN
    SELECT * INTO v_yeu_cau FROM public.yeu_cau_nap_rut_vi
    WHERE id = p_yeu_cau_id AND loai = 'RUT_TIEN' FOR UPDATE;
    IF NOT FOUND OR v_yeu_cau.trang_thai <> 'CHO_DUYET' THEN
        RAISE EXCEPTION 'Yêu cầu rút không còn chờ duyệt';
    END IF;
    UPDATE public.yeu_cau_nap_rut_vi
    SET trang_thai = 'DA_DUYET', ngay_xu_ly = NOW()
    WHERE id = p_yeu_cau_id;
    UPDATE public.giao_dich_vi
    SET loai = 'RUT_TIEN', noi_dung = 'Rút tiền đã được quản trị viên duyệt'
    WHERE yeu_cau_nap_rut_id = p_yeu_cau_id AND loai = 'YEU_CAU_RUT';
END;
$$;

CREATE OR REPLACE FUNCTION public.tu_choi_yeu_cau_rut_vi(
    p_yeu_cau_id BIGINT,
    p_ly_do TEXT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_yeu_cau public.yeu_cau_nap_rut_vi%ROWTYPE;
    v_so_du_moi NUMERIC;
BEGIN
    SELECT * INTO v_yeu_cau FROM public.yeu_cau_nap_rut_vi
    WHERE id = p_yeu_cau_id AND loai = 'RUT_TIEN' FOR UPDATE;
    IF NOT FOUND OR v_yeu_cau.trang_thai <> 'CHO_DUYET' THEN
        RAISE EXCEPTION 'Yêu cầu rút không còn chờ duyệt';
    END IF;
    UPDATE public.yeu_cau_nap_rut_vi
    SET trang_thai = 'TU_CHOI', ly_do_tu_choi = NULLIF(BTRIM(p_ly_do), ''),
        ngay_xu_ly = NOW()
    WHERE id = p_yeu_cau_id;
    UPDATE public.vi
    SET so_du = so_du + v_yeu_cau.so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_yeu_cau.vi_id RETURNING so_du INTO v_so_du_moi;
    INSERT INTO public.giao_dich_vi(
        vi_id, yeu_cau_nap_rut_id, loai, so_tien, so_du_sau, noi_dung
    ) VALUES (
        v_yeu_cau.vi_id, v_yeu_cau.id, 'HOAN_RUT', v_yeu_cau.so_tien,
        v_so_du_moi, 'Hoàn tiền do yêu cầu rút bị từ chối'
    );
END;
$$;

-- Trừ COD của nhân viên và cộng cho khách hàng trong cùng một transaction.
CREATE OR REPLACE FUNCTION public.tam_giu_cod_vi_shipper(
    p_nhan_vien_id BIGINT,
    p_don_hang_id BIGINT,
    p_so_tien NUMERIC
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_vi_nhan_vien_id BIGINT;
    v_vi_khach_hang_id BIGINT;
    v_khach_hang_id BIGINT;
    v_so_du_nhan_vien NUMERIC;
    v_so_du_khach_hang NUMERIC;
BEGIN
    IF COALESCE(p_so_tien, 0) <= 0 THEN RETURN; END IF;
    PERFORM pg_advisory_xact_lock(p_don_hang_id);

    SELECT dh.khach_hang_id INTO v_khach_hang_id
    FROM public.don_hang dh WHERE dh.id = p_don_hang_id;
    IF v_khach_hang_id IS NULL THEN RAISE EXCEPTION 'Đơn hàng không có khách hàng'; END IF;

    INSERT INTO public.vi(nhan_vien_id) VALUES (p_nhan_vien_id)
    ON CONFLICT (nhan_vien_id) DO UPDATE SET nhan_vien_id = EXCLUDED.nhan_vien_id
    RETURNING id, so_du INTO v_vi_nhan_vien_id, v_so_du_nhan_vien;

    IF EXISTS (SELECT 1 FROM public.giao_dich_vi
               WHERE vi_id = v_vi_nhan_vien_id AND don_hang_id = p_don_hang_id
                 AND loai = 'TRU_COD') THEN RETURN; END IF;
    IF v_so_du_nhan_vien < p_so_tien THEN
        RAISE EXCEPTION 'Số dư ví không đủ. Đơn COD %đ, số dư hiện tại %đ',
            ROUND(p_so_tien), ROUND(v_so_du_nhan_vien);
    END IF;

    UPDATE public.vi SET so_du = so_du - p_so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_vi_nhan_vien_id RETURNING so_du INTO v_so_du_nhan_vien;
    INSERT INTO public.giao_dich_vi(vi_id, don_hang_id, loai, so_tien, so_du_sau, noi_dung)
    VALUES (v_vi_nhan_vien_id, p_don_hang_id, 'TRU_COD', p_so_tien,
            v_so_du_nhan_vien, 'Khấu trừ tiền thu hộ khi giao thành công');

    INSERT INTO public.vi(khach_hang_id) VALUES (v_khach_hang_id)
    ON CONFLICT (khach_hang_id) DO UPDATE SET khach_hang_id = EXCLUDED.khach_hang_id
    RETURNING id INTO v_vi_khach_hang_id;
    UPDATE public.vi SET so_du = so_du + p_so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_vi_khach_hang_id RETURNING so_du INTO v_so_du_khach_hang;
    INSERT INTO public.giao_dich_vi(vi_id, don_hang_id, loai, so_tien, so_du_sau, noi_dung)
    VALUES (v_vi_khach_hang_id, p_don_hang_id, 'NHAN_COD', p_so_tien,
            v_so_du_khach_hang, 'Nhận tiền COD từ đơn giao thành công');
END;
$$;

CREATE OR REPLACE FUNCTION public.cong_thu_nhap_vi_shipper(
    p_nhan_vien_id BIGINT,
    p_don_hang_id BIGINT,
    p_so_tien NUMERIC
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_vi_id BIGINT; v_so_du_moi NUMERIC;
BEGIN
    IF COALESCE(p_so_tien, 0) <= 0 THEN RETURN; END IF;
    PERFORM pg_advisory_xact_lock(p_don_hang_id);
    INSERT INTO public.vi(nhan_vien_id) VALUES (p_nhan_vien_id)
    ON CONFLICT (nhan_vien_id) DO UPDATE SET nhan_vien_id = EXCLUDED.nhan_vien_id
    RETURNING id INTO v_vi_id;
    IF EXISTS (SELECT 1 FROM public.giao_dich_vi
               WHERE vi_id = v_vi_id AND don_hang_id = p_don_hang_id
                 AND loai = 'THU_NHAP_GIAO_HANG') THEN RETURN; END IF;
    UPDATE public.vi SET so_du = so_du + p_so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_vi_id RETURNING so_du INTO v_so_du_moi;
    INSERT INTO public.giao_dich_vi(vi_id, don_hang_id, loai, so_tien, so_du_sau, noi_dung)
    VALUES (v_vi_id, p_don_hang_id, 'THU_NHAP_GIAO_HANG', p_so_tien,
            v_so_du_moi, 'Cộng thu nhập khi giao hàng thành công');
END;
$$;

-- Tạo một dòng sao kê chuyển đổi cho số dư cũ của shipper.
INSERT INTO public.giao_dich_vi(
    vi_id, loai, so_tien, so_du_sau, noi_dung
)
SELECT v.id, 'DIEU_CHINH', v.so_du, v.so_du,
       'Chuyển số dư từ ví shipper cũ sang ví dùng chung'
FROM public.vi v
WHERE v.nhan_vien_id IS NOT NULL
  AND v.so_du > 0
  AND NOT EXISTS (
      SELECT 1 FROM public.giao_dich_vi gd
      WHERE gd.vi_id = v.id
        AND gd.noi_dung = 'Chuyển số dư từ ví shipper cũ sang ví dùng chung'
  );

-- Cộng bù COD của các đơn cũ đã khấu trừ khỏi ví shipper.
DO $$
DECLARE
    v_cu RECORD;
    v_vi_khach_hang_id BIGINT;
    v_so_du_moi NUMERIC;
BEGIN
    FOR v_cu IN
        SELECT gd.don_hang_id, gd.so_tien, dh.khach_hang_id
        FROM public.giao_dich_vi_shipper gd
        JOIN public.don_hang dh ON dh.id = gd.don_hang_id
        WHERE gd.loai = 'TAM_GIU_COD'
          AND dh.khach_hang_id IS NOT NULL
    LOOP
        INSERT INTO public.vi(khach_hang_id)
        VALUES (v_cu.khach_hang_id)
        ON CONFLICT (khach_hang_id) DO UPDATE
            SET khach_hang_id = EXCLUDED.khach_hang_id
        RETURNING id INTO v_vi_khach_hang_id;

        IF NOT EXISTS (
            SELECT 1 FROM public.giao_dich_vi gd
            WHERE gd.vi_id = v_vi_khach_hang_id
              AND gd.don_hang_id = v_cu.don_hang_id
              AND gd.loai = 'NHAN_COD'
        ) THEN
            UPDATE public.vi
            SET so_du = so_du + v_cu.so_tien,
                ngay_cap_nhat = NOW()
            WHERE id = v_vi_khach_hang_id
            RETURNING so_du INTO v_so_du_moi;

            INSERT INTO public.giao_dich_vi(
                vi_id, don_hang_id, loai, so_tien, so_du_sau, noi_dung
            ) VALUES (
                v_vi_khach_hang_id, v_cu.don_hang_id, 'NHAN_COD',
                v_cu.so_tien, v_so_du_moi,
                'Cộng bù tiền COD từ dữ liệu giao hàng cũ'
            );
        END IF;
    END LOOP;
END;
$$;

