CREATE INDEX IF NOT EXISTS idx_giao_dich_vi_lich_su
    ON public.giao_dich_vi(vi_id, ngay_tao DESC);

CREATE TABLE IF NOT EXISTS public.yeu_cau_nap_vi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vi_id BIGINT NOT NULL REFERENCES public.vi(id) ON DELETE CASCADE,
    so_tien NUMERIC(14,2) NOT NULL CHECK (so_tien >= 10000),
    phuong_thuc VARCHAR(30) NOT NULL DEFAULT 'CHUYEN_KHOAN',
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'CHO_DUYET'
        CHECK (trang_thai IN ('CHO_DUYET', 'DA_DUYET', 'TU_CHOI')),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_xu_ly TIMESTAMPTZ
);

