CREATE TABLE IF NOT EXISTS public.vi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    khach_hang_id BIGINT UNIQUE
        REFERENCES public.khach_hang(id) ON DELETE CASCADE,
    nhan_vien_id BIGINT UNIQUE
        REFERENCES public.nhan_vien(id) ON DELETE CASCADE,
    so_du NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (so_du >= 0),
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_vi_chi_mot_chu_so_huu CHECK (
        (khach_hang_id IS NOT NULL AND nhan_vien_id IS NULL)
        OR (khach_hang_id IS NULL AND nhan_vien_id IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS public.giao_dich_vi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vi_id BIGINT NOT NULL REFERENCES public.vi(id) ON DELETE RESTRICT,
    don_hang_id BIGINT REFERENCES public.don_hang(id) ON DELETE RESTRICT,
    loai VARCHAR(40) NOT NULL CHECK (loai IN (
        'NAP_TIEN', 'RUT_TIEN', 'TRU_COD', 'NHAN_COD',
        'HOAN_COD', 'THU_NHAP_GIAO_HANG', 'DIEU_CHINH'
    )),
    so_tien NUMERIC(14,2) NOT NULL CHECK (so_tien > 0),
    so_du_sau NUMERIC(14,2) NOT NULL CHECK (so_du_sau >= 0),
    noi_dung TEXT,
    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.giao_dich_vi
    DROP CONSTRAINT IF EXISTS giao_dich_vi_loai_check;
ALTER TABLE public.giao_dich_vi
    DROP CONSTRAINT IF EXISTS chk_giao_dich_vi_loai;
