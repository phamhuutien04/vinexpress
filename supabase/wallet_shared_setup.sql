-- Chuyển số dư shipper cũ sang ví chung, không cộng trùng khi chạy lại.
INSERT INTO public.vi(nhan_vien_id, so_du, ngay_cap_nhat)
SELECT vs.nhan_vien_id, vs.so_du, vs.ngay_cap_nhat
FROM public.vi_shipper vs
ON CONFLICT (nhan_vien_id) DO NOTHING;

-- Chuyển các yêu cầu nạp cũ sang bảng yêu cầu nạp dùng chung.
INSERT INTO public.yeu_cau_nap_vi(
    vi_id, so_tien, phuong_thuc, trang_thai, ngay_tao, ngay_xu_ly
)
SELECT v.id, yc.so_tien, yc.phuong_thuc, yc.trang_thai,
       yc.ngay_tao, yc.ngay_xu_ly
FROM public.yeu_cau_nap_vi_shipper yc
JOIN public.vi v ON v.nhan_vien_id = yc.nhan_vien_id
WHERE NOT EXISTS (
    SELECT 1 FROM public.yeu_cau_nap_vi moi
    WHERE moi.vi_id = v.id
      AND moi.so_tien = yc.so_tien
      AND moi.phuong_thuc = yc.phuong_thuc
      AND moi.ngay_tao = yc.ngay_tao
);

-- Gộp dữ liệu từ hai bảng yêu cầu cũ vào bảng nạp/rút dùng chung.
INSERT INTO public.yeu_cau_nap_rut_vi(
    vi_id, loai, so_tien, phuong_thuc, trang_thai,
    ngay_tao, ngay_xu_ly, nguon_bang, nguon_id
)
SELECT n.vi_id, 'NAP_TIEN', n.so_tien, n.phuong_thuc, n.trang_thai,
       n.ngay_tao, n.ngay_xu_ly, 'yeu_cau_nap_vi', n.id
FROM public.yeu_cau_nap_vi n
ON CONFLICT (nguon_bang, nguon_id) WHERE nguon_bang IS NOT NULL AND nguon_id IS NOT NULL
DO NOTHING;

INSERT INTO public.yeu_cau_nap_rut_vi(
    vi_id, loai, so_tien, ngan_hang, so_tai_khoan, chu_tai_khoan,
    trang_thai, ly_do_tu_choi, ngay_tao, ngay_xu_ly, nguon_bang, nguon_id
)
SELECT r.vi_id, 'RUT_TIEN', r.so_tien, r.ngan_hang, r.so_tai_khoan,
       r.chu_tai_khoan, r.trang_thai, r.ly_do_tu_choi,
       r.ngay_tao, r.ngay_xu_ly, 'yeu_cau_rut_vi', r.id
FROM public.yeu_cau_rut_vi r
ON CONFLICT (nguon_bang, nguon_id) WHERE nguon_bang IS NOT NULL AND nguon_id IS NOT NULL
DO NOTHING;

-- Chuyển liên kết giao dịch rút cũ sang ID yêu cầu dùng chung.
UPDATE public.giao_dich_vi gd
SET yeu_cau_nap_rut_id = moi.id
FROM public.yeu_cau_nap_rut_vi moi
WHERE gd.yeu_cau_rut_id IS NOT NULL
  AND moi.nguon_bang = 'yeu_cau_rut_vi'
  AND moi.nguon_id = gd.yeu_cau_rut_id
  AND gd.yeu_cau_nap_rut_id IS NULL;

DROP FUNCTION IF EXISTS public.thong_tin_vi();
CREATE OR REPLACE FUNCTION public.thong_tin_vi()
RETURNS TABLE (
    so_du NUMERIC,
    tong_cho_nap NUMERIC,
    tong_cho_rut NUMERIC
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_khach_hang_id BIGINT;
    v_nhan_vien_id BIGINT;
    v_vi_id BIGINT;
BEGIN
    SELECT kh.id INTO v_khach_hang_id
    FROM public.khach_hang kh WHERE kh.auth_user_id = auth.uid();

    IF v_khach_hang_id IS NULL THEN
        SELECT nv.id INTO v_nhan_vien_id
        FROM public.nhan_vien nv WHERE nv.auth_user_id = auth.uid();
    END IF;

    IF v_khach_hang_id IS NOT NULL THEN
        INSERT INTO public.vi(khach_hang_id) VALUES (v_khach_hang_id)
        ON CONFLICT (khach_hang_id) DO UPDATE SET khach_hang_id = EXCLUDED.khach_hang_id
        RETURNING id INTO v_vi_id;
    ELSIF v_nhan_vien_id IS NOT NULL THEN
        INSERT INTO public.vi(nhan_vien_id) VALUES (v_nhan_vien_id)
        ON CONFLICT (nhan_vien_id) DO UPDATE SET nhan_vien_id = EXCLUDED.nhan_vien_id
        RETURNING id INTO v_vi_id;
    ELSE
        RAISE EXCEPTION 'Không tìm thấy người dùng của ví';
    END IF;

    RETURN QUERY
    SELECT v.so_du,
           COALESCE((SELECT SUM(n.so_tien) FROM public.yeu_cau_nap_rut_vi n
                     WHERE n.vi_id = v.id AND n.loai = 'NAP_TIEN'
                       AND n.trang_thai = 'CHO_DUYET'), 0)::NUMERIC,
           COALESCE((SELECT SUM(r.so_tien) FROM public.yeu_cau_nap_rut_vi r
                     WHERE r.vi_id = v.id AND r.loai = 'RUT_TIEN'
                       AND r.trang_thai = 'CHO_DUYET'), 0)::NUMERIC
    FROM public.vi v
    WHERE v.id = v_vi_id
    GROUP BY v.id, v.so_du;
END;
$$;

CREATE OR REPLACE FUNCTION public.lich_su_giao_dich_vi()
RETURNS TABLE (
    id BIGINT, loai VARCHAR, so_tien NUMERIC, so_du_sau NUMERIC,
    noi_dung TEXT, ma_van_don VARCHAR, ngay_tao TIMESTAMPTZ
)
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
    SELECT gd.id, gd.loai, gd.so_tien, gd.so_du_sau, gd.noi_dung,
           dh.ma_van_don, gd.ngay_tao
    FROM public.giao_dich_vi gd
    JOIN public.vi v ON v.id = gd.vi_id
    LEFT JOIN public.don_hang dh ON dh.id = gd.don_hang_id
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid()
    ORDER BY gd.ngay_tao DESC
    LIMIT 100;
$$;

CREATE OR REPLACE FUNCTION public.tao_yeu_cau_nap_vi(
    p_so_tien NUMERIC,
    p_phuong_thuc TEXT DEFAULT 'CHUYEN_KHOAN'
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_vi_id BIGINT;
    v_id BIGINT;
BEGIN
    IF p_so_tien < 10000 THEN
        RAISE EXCEPTION 'Số tiền nạp tối thiểu là 10.000đ';
    END IF;

    PERFORM public.thong_tin_vi();
    SELECT v.id INTO v_vi_id
    FROM public.vi v
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid();

    INSERT INTO public.yeu_cau_nap_rut_vi(
        vi_id, loai, so_tien, phuong_thuc
    ) VALUES (
        v_vi_id, 'NAP_TIEN', p_so_tien, UPPER(BTRIM(p_phuong_thuc))
    )
    RETURNING id INTO v_id;
    RETURN v_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.duyet_yeu_cau_nap_vi(p_yeu_cau_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_yeu_cau public.yeu_cau_nap_rut_vi%ROWTYPE;
    v_so_du_moi NUMERIC;
BEGIN
    SELECT * INTO v_yeu_cau FROM public.yeu_cau_nap_rut_vi
    WHERE id = p_yeu_cau_id AND loai = 'NAP_TIEN' FOR UPDATE;
    IF NOT FOUND OR v_yeu_cau.trang_thai <> 'CHO_DUYET' THEN
        RAISE EXCEPTION 'Yêu cầu nạp không còn chờ duyệt';
    END IF;

    UPDATE public.vi SET so_du = so_du + v_yeu_cau.so_tien, ngay_cap_nhat = NOW()
    WHERE id = v_yeu_cau.vi_id RETURNING so_du INTO v_so_du_moi;
    UPDATE public.yeu_cau_nap_rut_vi SET trang_thai = 'DA_DUYET', ngay_xu_ly = NOW()
    WHERE id = p_yeu_cau_id;
    INSERT INTO public.giao_dich_vi(vi_id, loai, so_tien, so_du_sau, noi_dung)
    VALUES (v_yeu_cau.vi_id, 'NAP_TIEN', v_yeu_cau.so_tien, v_so_du_moi, 'Nạp tiền vào ví');
END;
$$;

CREATE OR REPLACE FUNCTION public.lien_ket_tai_khoan_ngan_hang_vi(
    p_ngan_hang TEXT,
    p_so_tai_khoan TEXT,
    p_chu_tai_khoan TEXT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE v_vi_id BIGINT;
BEGIN
    IF NULLIF(BTRIM(p_ngan_hang), '') IS NULL
       OR NULLIF(BTRIM(p_so_tai_khoan), '') IS NULL
       OR NULLIF(BTRIM(p_chu_tai_khoan), '') IS NULL THEN
        RAISE EXCEPTION 'Vui lòng nhập đầy đủ thông tin tài khoản ngân hàng';
    END IF;
    PERFORM public.thong_tin_vi();
    SELECT v.id INTO v_vi_id
    FROM public.vi v
    LEFT JOIN public.khach_hang kh ON kh.id = v.khach_hang_id
    LEFT JOIN public.nhan_vien nv ON nv.id = v.nhan_vien_id
    WHERE kh.auth_user_id = auth.uid() OR nv.auth_user_id = auth.uid();

    INSERT INTO public.tai_khoan_ngan_hang_vi(
        vi_id, ngan_hang, so_tai_khoan, chu_tai_khoan
    ) VALUES (
        v_vi_id, UPPER(BTRIM(p_ngan_hang)), BTRIM(p_so_tai_khoan),
        UPPER(BTRIM(p_chu_tai_khoan))
    ) ON CONFLICT (vi_id) DO UPDATE SET
        ngan_hang = EXCLUDED.ngan_hang,
        so_tai_khoan = EXCLUDED.so_tai_khoan,
        chu_tai_khoan = EXCLUDED.chu_tai_khoan,
        ngay_cap_nhat = NOW();
END;
$$;

