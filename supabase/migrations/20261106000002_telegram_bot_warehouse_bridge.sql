ALTER TABLE public.kho_hang ADD COLUMN IF NOT EXISTS telegram_chat_id BIGINT;
CREATE TABLE IF NOT EXISTS public.tin_nhan_telegram_kho (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kho_hang_id BIGINT NOT NULL REFERENCES public.kho_hang(id) ON DELETE CASCADE,
  nhan_vien_id BIGINT REFERENCES public.nhan_vien(id) ON DELETE SET NULL,
  noi_dung TEXT NOT NULL CHECK (char_length(BTRIM(noi_dung)) BETWEEN 1 AND 1000),
  telegram_message_id BIGINT, thoi_gian TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_tin_nhan_telegram_kho ON public.tin_nhan_telegram_kho(kho_hang_id, thoi_gian DESC);
ALTER TABLE public.tin_nhan_telegram_kho ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Nhan vien kho xem tin bot cung kho" ON public.tin_nhan_telegram_kho;
CREATE POLICY "Nhan vien kho xem tin bot cung kho" ON public.tin_nhan_telegram_kho FOR SELECT TO authenticated USING (
  EXISTS (SELECT 1 FROM public.nhan_vien nv WHERE nv.auth_user_id = auth.uid() AND nv.kho_hang_id = tin_nhan_telegram_kho.kho_hang_id AND nv.vai_tro = 'NHAN_VIEN_KHO' AND nv.trang_thai = 'HOAT_DONG' AND nv.trang_thai_duyet = 'DA_DUYET')
);
CREATE OR REPLACE FUNCTION public.nhan_vien_kho_tin_nhan_telegram()
RETURNS TABLE(id BIGINT, noi_dung TEXT, thoi_gian TIMESTAMPTZ, nguoi_gui_ten VARCHAR, la_cua_toi BOOLEAN)
LANGUAGE plpgsql SECURITY DEFINER STABLE SET search_path = public AS $$
DECLARE v_nv public.nhan_vien%ROWTYPE;
BEGIN
  SELECT * INTO v_nv FROM public.nhan_vien WHERE auth_user_id = auth.uid() AND vai_tro = 'NHAN_VIEN_KHO' AND trang_thai = 'HOAT_DONG' AND trang_thai_duyet = 'DA_DUYET';
  IF NOT FOUND OR v_nv.kho_hang_id IS NULL THEN RAISE EXCEPTION 'Nhân viên chưa được gán kho'; END IF;
  RETURN QUERY SELECT t.id,t.noi_dung,t.thoi_gian,nv.ho_ten::VARCHAR,(t.nhan_vien_id=v_nv.id)
  FROM public.tin_nhan_telegram_kho t LEFT JOIN public.nhan_vien nv ON nv.id=t.nhan_vien_id
  WHERE t.kho_hang_id=v_nv.kho_hang_id ORDER BY t.thoi_gian ASC LIMIT 300;
END; $$;
REVOKE ALL ON FUNCTION public.nhan_vien_kho_tin_nhan_telegram() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.nhan_vien_kho_tin_nhan_telegram() TO authenticated;
NOTIFY pgrst, 'reload schema';
