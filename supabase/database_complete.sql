-- ============================================================
-- 2. BẢNG KHÁCH HÀNG
-- ============================================================

CREATE TABLE khach_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ho_ten VARCHAR(255) NOT NULL,
    so_dien_thoai VARCHAR(20) NOT NULL,
    email VARCHAR(255),
    mat_khau TEXT NOT NULL,

    dia_chi TEXT,
    avt TEXT,

    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    trang_thai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG',

    CONSTRAINT uq_khach_hang_sdt UNIQUE (so_dien_thoai),
    CONSTRAINT uq_khach_hang_email UNIQUE (email),

    CONSTRAINT chk_khach_hang_trang_thai CHECK (
        trang_thai IN (
            'HOAT_DONG',
            'TAM_KHOA',
            'DA_KHOA'
        )
    )
);

-- ============================================================
-- 3. BẢNG KHU VỰC
-- ============================================================

CREATE TABLE khu_vuc (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ten_khu_vuc VARCHAR(255) NOT NULL,
    tinh_thanh VARCHAR(255) NOT NULL,
    quan_huyen VARCHAR(255),
    phuong_xa VARCHAR(255),

    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_khu_vuc UNIQUE (
        ten_khu_vuc,
        tinh_thanh,
        quan_huyen,
        phuong_xa
    )
);

-- ============================================================
-- 4. BẢNG KHO HÀNG
-- ============================================================

CREATE TABLE kho_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ma_kho VARCHAR(50) NOT NULL,
    ten_kho VARCHAR(255) NOT NULL,
    dia_chi TEXT NOT NULL,

    khu_vuc_id BIGINT NOT NULL,

    so_dien_thoai VARCHAR(20),

    trang_thai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG',

    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_kho_hang_ma_kho UNIQUE (ma_kho),

    CONSTRAINT fk_kho_hang_khu_vuc
        FOREIGN KEY (khu_vuc_id)
        REFERENCES khu_vuc(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT chk_kho_hang_trang_thai CHECK (
        trang_thai IN (
            'HOAT_DONG',
            'TAM_NGUNG',
            'DA_DONG_CUA'
        )
    )
);

-- ============================================================
-- 5. BẢNG NHÂN VIÊN
-- ============================================================

CREATE TABLE nhan_vien (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    kho_hang_id BIGINT,

    ho_ten VARCHAR(255) NOT NULL,
    so_dien_thoai VARCHAR(20) NOT NULL,
    email VARCHAR(255),

    mat_khau TEXT NOT NULL,
    dia_chi TEXT,

    so_cccd VARCHAR(20),

    anh_cccd_truoc TEXT,
    anh_cccd_sau TEXT,
    anh_khuon_mat TEXT,

    vai_tro VARCHAR(30) NOT NULL,

    trang_thai_duyet VARCHAR(30) NOT NULL DEFAULT 'CHO_DUYET',
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG',

    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_nhan_vien_sdt UNIQUE (so_dien_thoai),
    CONSTRAINT uq_nhan_vien_email UNIQUE (email),
    CONSTRAINT uq_nhan_vien_cccd UNIQUE (so_cccd),

    CONSTRAINT fk_nhan_vien_kho_hang
        FOREIGN KEY (kho_hang_id)
        REFERENCES kho_hang(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT chk_nhan_vien_vai_tro CHECK (
        vai_tro IN (
            'ADMIN',
            'QUAN_LY_KHO',
            'NHAN_VIEN_KHO',
            'VAN_CHUYEN',
            'SHIPPER'
        )
    ),

    CONSTRAINT chk_nhan_vien_trang_thai_duyet CHECK (
        trang_thai_duyet IN (
            'CHO_DUYET',
            'DA_DUYET',
            'TU_CHOI'
        )
    ),

    CONSTRAINT chk_nhan_vien_trang_thai CHECK (
        trang_thai IN (
            'HOAT_DONG',
            'TAM_KHOA',
            'DA_NGHI'
        )
    )
);

-- ============================================================
-- 6. BẢNG ĐƠN HÀNG
-- ============================================================

CREATE TABLE don_hang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    ma_van_don VARCHAR(50) NOT NULL,

    -- Có thể dùng UUID này để tạo nội dung mã QR.
    ma_qr UUID NOT NULL DEFAULT GEN_RANDOM_UUID(),

    khach_hang_id BIGINT NOT NULL,

    nguoi_gui_ten VARCHAR(255) NOT NULL,
    nguoi_gui_dia_chi TEXT NOT NULL,
    nguoi_gui_sdt VARCHAR(20) NOT NULL,

    nguoi_nhan_ten VARCHAR(255) NOT NULL,
    nguoi_nhan_dia_chi TEXT NOT NULL,
    nguoi_nhan_sdt VARCHAR(20) NOT NULL,

    can_nang NUMERIC(12,3) NOT NULL DEFAULT 0,
    gia_tri_hang NUMERIC(18,2) NOT NULL DEFAULT 0,
    phi_van_chuyen NUMERIC(18,2) NOT NULL DEFAULT 0,
    cod NUMERIC(18,2) NOT NULL DEFAULT 0,

    kho_gui_id BIGINT NOT NULL,
    kho_dich_id BIGINT NOT NULL,

    -- Kho hiện tại của đơn hàng.
    kho_hien_tai_id BIGINT,

    -- Nhân viên đang giữ hoặc đang xử lý đơn hàng.
    nhan_vien_hien_tai_id BIGINT,

    trang_thai VARCHAR(50) NOT NULL DEFAULT 'CHO_LAY_HANG',

    ghi_chu TEXT,

    ngay_tao TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_cap_nhat TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ngay_lay_hang TIMESTAMPTZ,
    ngay_giao_hang TIMESTAMPTZ,

    CONSTRAINT uq_don_hang_ma_van_don UNIQUE (ma_van_don),
    CONSTRAINT uq_don_hang_ma_qr UNIQUE (ma_qr),

    CONSTRAINT fk_don_hang_khach_hang
        FOREIGN KEY (khach_hang_id)
        REFERENCES khach_hang(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_don_hang_kho_gui
        FOREIGN KEY (kho_gui_id)
        REFERENCES kho_hang(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_don_hang_kho_dich
        FOREIGN KEY (kho_dich_id)
        REFERENCES kho_hang(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_don_hang_kho_hien_tai
        FOREIGN KEY (kho_hien_tai_id)
        REFERENCES kho_hang(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_don_hang_nhan_vien_hien_tai
        FOREIGN KEY (nhan_vien_hien_tai_id)
        REFERENCES nhan_vien(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT chk_don_hang_can_nang CHECK (can_nang >= 0),
    CONSTRAINT chk_don_hang_gia_tri CHECK (gia_tri_hang >= 0),
    CONSTRAINT chk_don_hang_phi CHECK (phi_van_chuyen >= 0),
    CONSTRAINT chk_don_hang_cod CHECK (cod >= 0),

    CONSTRAINT chk_don_hang_kho CHECK (
        kho_gui_id <> kho_dich_id
    ),

    CONSTRAINT chk_don_hang_trang_thai CHECK (
        trang_thai IN (
            'CHO_LAY_HANG',
            'DA_LAY_HANG',
            'DANG_VAN_CHUYEN',
            'DEN_KHO_TRUNG_CHUYEN',
            'DEN_KHO_DICH',
            'GIAO_CHO_SHIPPER',
            'DANG_GIAO_HANG',
            'DA_GIAO_HANG',
            'GIAO_HANG_THAT_BAI',
            'HOAN_HANG',
            'DA_HUY'
        )
    )
);

