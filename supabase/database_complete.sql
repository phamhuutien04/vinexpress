CREATE OR REPLACE FUNCTION quet_qr_don_hang(
    p_ma_van_don TEXT,
    p_nhan_vien_id BIGINT,
    p_kho_id BIGINT DEFAULT NULL,
    p_su_kien TEXT DEFAULT 'TU_DONG',
    p_minh_chung TEXT DEFAULT NULL,
    p_ghi_chu TEXT DEFAULT NULL,
    p_vi_do DOUBLE PRECISION DEFAULT NULL,
    p_kinh_do DOUBLE PRECISION DEFAULT NULL
)
RETURNS TABLE (
    thanh_cong BOOLEAN,
    don_hang_id BIGINT,
    ma_van_don TEXT,
    trang_thai_cu TEXT,
    trang_thai_moi TEXT,
    hanh_dong TEXT,
    ten_kho TEXT,
    thoi_gian TIMESTAMPTZ
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_don_hang don_hang%ROWTYPE;
    v_nhan_vien nhan_vien%ROWTYPE;
    v_kho kho_hang%ROWTYPE;

    v_su_kien TEXT;
    v_trang_thai_cu TEXT;
    v_trang_thai_moi TEXT;
    v_hanh_dong TEXT;
    v_ten_kho TEXT;
BEGIN
    -- --------------------------------------------------------
    -- Kiểm tra mã vận đơn
    -- --------------------------------------------------------
    IF p_ma_van_don IS NULL OR BTRIM(p_ma_van_don) = '' THEN
        RAISE EXCEPTION 'Mã vận đơn không được để trống';
    END IF;

    -- Khóa đơn hàng trong lúc xử lý để tránh quét đồng thời.
    SELECT *
    INTO v_don_hang
    FROM don_hang
    WHERE UPPER(ma_van_don) = UPPER(BTRIM(p_ma_van_don))
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Không tìm thấy đơn hàng có mã vận đơn: %',
            p_ma_van_don;
    END IF;

    -- --------------------------------------------------------
    -- Kiểm tra nhân viên
    -- --------------------------------------------------------
    SELECT *
    INTO v_nhan_vien
    FROM nhan_vien
    WHERE id = p_nhan_vien_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Không tìm thấy nhân viên ID: %',
            p_nhan_vien_id;
    END IF;

    IF v_nhan_vien.trang_thai <> 'HOAT_DONG' THEN
        RAISE EXCEPTION 'Tài khoản nhân viên không hoạt động';
    END IF;

    IF v_nhan_vien.trang_thai_duyet <> 'DA_DUYET' THEN
        RAISE EXCEPTION 'Tài khoản nhân viên chưa được duyệt';
    END IF;

    -- --------------------------------------------------------
    -- Xác định kho quét
    -- Nếu không truyền kho thì lấy kho của nhân viên.
    -- --------------------------------------------------------
    IF p_kho_id IS NULL THEN
        p_kho_id := v_nhan_vien.kho_hang_id;
    END IF;

    IF p_kho_id IS NOT NULL THEN
        SELECT *
        INTO v_kho
        FROM kho_hang
        WHERE id = p_kho_id;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Không tìm thấy kho hàng ID: %',
                p_kho_id;
        END IF;

        v_ten_kho := v_kho.ten_kho;
    ELSE
        v_ten_kho := NULL;
    END IF;

    -- Nhân viên kho chỉ được thao tác tại kho của mình.
    IF v_nhan_vien.vai_tro IN ('QUAN_LY_KHO', 'NHAN_VIEN_KHO')
       AND v_nhan_vien.kho_hang_id IS NOT NULL
       AND p_kho_id IS DISTINCT FROM v_nhan_vien.kho_hang_id THEN
        RAISE EXCEPTION
            'Nhân viên kho chỉ được quét đơn tại kho được phân công';
    END IF;

    v_su_kien := UPPER(COALESCE(NULLIF(BTRIM(p_su_kien), ''), 'TU_DONG'));
    v_trang_thai_cu := v_don_hang.trang_thai;

    -- --------------------------------------------------------
    -- Tự xác định sự kiện theo vai trò và trạng thái
    -- --------------------------------------------------------
    IF v_su_kien = 'TU_DONG' THEN

        -- Nhân viên vận chuyển lấy hàng từ khách hàng.
        IF v_nhan_vien.vai_tro = 'VAN_CHUYEN'
           AND v_don_hang.trang_thai = 'CHO_LAY_HANG' THEN

            v_su_kien := 'LAY_HANG';

        -- Quản lý kho hoặc nhân viên kho tiếp nhận hàng.
        ELSIF v_nhan_vien.vai_tro IN ('QUAN_LY_KHO', 'NHAN_VIEN_KHO')
              AND v_don_hang.trang_thai IN (
                  'DA_LAY_HANG',
                  'DANG_VAN_CHUYEN',
                  'GIAO_CHO_SHIPPER',
                  'DANG_GIAO_HANG'
              ) THEN

            v_su_kien := 'DEN_KHO';

        -- Nhân viên vận chuyển hoặc shipper nhận hàng từ kho.
        ELSIF v_nhan_vien.vai_tro IN ('VAN_CHUYEN', 'SHIPPER')
              AND v_don_hang.trang_thai IN (
                  'DEN_KHO_TRUNG_CHUYEN',
                  'DEN_KHO_DICH'
              ) THEN

            v_su_kien := 'GIAO_CHO_SHIPPER';

        ELSE
            RAISE EXCEPTION
                'Không xác định được hành động tự động. Vai trò: %, trạng thái đơn: %',
                v_nhan_vien.vai_tro,
                v_don_hang.trang_thai;
        END IF;
    END IF;

    -- --------------------------------------------------------
    -- SỰ KIỆN 1: NHÂN VIÊN VẬN CHUYỂN LẤY HÀNG
    -- --------------------------------------------------------
    IF v_su_kien = 'LAY_HANG' THEN

        IF v_nhan_vien.vai_tro <> 'VAN_CHUYEN' THEN
            RAISE EXCEPTION
                'Chỉ nhân viên vận chuyển được xác nhận lấy hàng';
        END IF;

        IF v_don_hang.trang_thai <> 'CHO_LAY_HANG' THEN
            RAISE EXCEPTION
                'Đơn hàng phải ở trạng thái CHO_LAY_HANG. Trạng thái hiện tại: %',
                v_don_hang.trang_thai;
        END IF;

        v_trang_thai_moi := 'DA_LAY_HANG';
        v_hanh_dong := 'Đã lấy hàng từ khách hàng';

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            nhan_vien_hien_tai_id = p_nhan_vien_id,
            kho_hien_tai_id = NULL,
            ngay_lay_hang = NOW()
        WHERE id = v_don_hang.id;

    -- --------------------------------------------------------
    -- SỰ KIỆN 2: QUẢN LÝ KHO TIẾP NHẬN HÀNG
    -- --------------------------------------------------------
    ELSIF v_su_kien = 'DEN_KHO' THEN

        IF v_nhan_vien.vai_tro NOT IN (
            'QUAN_LY_KHO',
            'NHAN_VIEN_KHO'
        ) THEN
            RAISE EXCEPTION
                'Chỉ quản lý kho hoặc nhân viên kho được tiếp nhận hàng';
        END IF;

        IF p_kho_id IS NULL THEN
            RAISE EXCEPTION
                'Phải truyền kho_id hoặc gán kho_hang_id cho nhân viên';
        END IF;

        IF v_don_hang.trang_thai IN (
            'DA_GIAO_HANG',
            'DA_HUY',
            'HOAN_HANG'
        ) THEN
            RAISE EXCEPTION
                'Không thể tiếp nhận đơn ở trạng thái: %',
                v_don_hang.trang_thai;
        END IF;

        IF v_don_hang.kho_hien_tai_id = p_kho_id
           AND v_don_hang.trang_thai IN (
               'DEN_KHO_TRUNG_CHUYEN',
               'DEN_KHO_DICH'
           ) THEN
            RAISE EXCEPTION
                'Đơn hàng đã được quét tại kho này';
        END IF;

        IF p_kho_id = v_don_hang.kho_dich_id THEN
            v_trang_thai_moi := 'DEN_KHO_DICH';
            v_hanh_dong := 'Đã đến kho đích ' || v_kho.ten_kho;
        ELSE
            v_trang_thai_moi := 'DEN_KHO_TRUNG_CHUYEN';
            v_hanh_dong := 'Đã đến kho ' || v_kho.ten_kho;
        END IF;

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            kho_hien_tai_id = p_kho_id,
            nhan_vien_hien_tai_id = p_nhan_vien_id
        WHERE id = v_don_hang.id;

    -- --------------------------------------------------------
    -- SỰ KIỆN 3: GIAO ĐƠN CHO NHÂN VIÊN VẬN CHUYỂN/SHIPPER
    -- --------------------------------------------------------
    ELSIF v_su_kien = 'GIAO_CHO_SHIPPER' THEN

        IF v_nhan_vien.vai_tro NOT IN (
            'VAN_CHUYEN',
            'SHIPPER'
        ) THEN
            RAISE EXCEPTION
                'Chỉ nhân viên vận chuyển hoặc shipper được nhận hàng từ kho';
        END IF;

        IF v_don_hang.trang_thai NOT IN (
            'DEN_KHO_TRUNG_CHUYEN',
            'DEN_KHO_DICH'
        ) THEN
            RAISE EXCEPTION
                'Đơn hàng chưa được kho tiếp nhận. Trạng thái hiện tại: %',
                v_don_hang.trang_thai;
        END IF;

        v_trang_thai_moi := 'GIAO_CHO_SHIPPER';

        IF v_nhan_vien.vai_tro = 'SHIPPER' THEN
            v_hanh_dong :=
                'Kho đã giao hàng cho shipper ' || v_nhan_vien.ho_ten;
        ELSE
            v_hanh_dong :=
                'Kho đã giao hàng cho nhân viên vận chuyển '
                || v_nhan_vien.ho_ten;
        END IF;

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            nhan_vien_hien_tai_id = p_nhan_vien_id
        WHERE id = v_don_hang.id;

    -- --------------------------------------------------------
    -- SỰ KIỆN 4: SHIPPER BẮT ĐẦU GIAO HÀNG
    -- --------------------------------------------------------
    ELSIF v_su_kien = 'BAT_DAU_GIAO_HANG' THEN

        IF v_nhan_vien.vai_tro NOT IN (
            'VAN_CHUYEN',
            'SHIPPER'
        ) THEN
            RAISE EXCEPTION
                'Chỉ nhân viên vận chuyển hoặc shipper được giao hàng';
        END IF;

        IF v_don_hang.trang_thai <> 'GIAO_CHO_SHIPPER' THEN
            RAISE EXCEPTION
                'Đơn hàng phải ở trạng thái GIAO_CHO_SHIPPER';
        END IF;

        v_trang_thai_moi := 'DANG_GIAO_HANG';
        v_hanh_dong :=
            'Nhân viên ' || v_nhan_vien.ho_ten || ' bắt đầu giao hàng';

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            nhan_vien_hien_tai_id = p_nhan_vien_id
        WHERE id = v_don_hang.id;

    -- --------------------------------------------------------
    -- SỰ KIỆN 5: GIAO HÀNG THÀNH CÔNG
    -- Phải có ảnh minh chứng.
    -- --------------------------------------------------------
    ELSIF v_su_kien = 'GIAO_HANG_THANH_CONG' THEN

        IF v_nhan_vien.vai_tro NOT IN (
            'VAN_CHUYEN',
            'SHIPPER'
        ) THEN
            RAISE EXCEPTION
                'Chỉ nhân viên vận chuyển hoặc shipper được xác nhận giao hàng';
        END IF;

        IF v_don_hang.trang_thai NOT IN (
            'GIAO_CHO_SHIPPER',
            'DANG_GIAO_HANG'
        ) THEN
            RAISE EXCEPTION
                'Đơn hàng chưa được giao cho shipper';
        END IF;

        IF p_minh_chung IS NULL OR BTRIM(p_minh_chung) = '' THEN
            RAISE EXCEPTION
                'Phải có ảnh hoặc đường dẫn minh chứng giao hàng';
        END IF;

        v_trang_thai_moi := 'DA_GIAO_HANG';
        v_hanh_dong := 'Đã giao hàng thành công cho khách hàng';

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            nhan_vien_hien_tai_id = p_nhan_vien_id,
            kho_hien_tai_id = NULL,
            ngay_giao_hang = NOW()
        WHERE id = v_don_hang.id;

    -- --------------------------------------------------------
    -- SỰ KIỆN 6: GIAO HÀNG THẤT BẠI
    -- --------------------------------------------------------
    ELSIF v_su_kien = 'GIAO_HANG_THAT_BAI' THEN

        IF v_nhan_vien.vai_tro NOT IN (
            'VAN_CHUYEN',
            'SHIPPER'
        ) THEN
            RAISE EXCEPTION
                'Chỉ nhân viên vận chuyển hoặc shipper được cập nhật giao thất bại';
        END IF;

        IF v_don_hang.trang_thai NOT IN (
            'GIAO_CHO_SHIPPER',
            'DANG_GIAO_HANG'
        ) THEN
            RAISE EXCEPTION
                'Đơn hàng chưa ở quá trình giao hàng';
        END IF;

        IF p_ghi_chu IS NULL OR BTRIM(p_ghi_chu) = '' THEN
            RAISE EXCEPTION
                'Phải nhập lý do giao hàng thất bại';
        END IF;

        v_trang_thai_moi := 'GIAO_HANG_THAT_BAI';
        v_hanh_dong := 'Giao hàng thất bại';

        UPDATE don_hang
        SET
            trang_thai = v_trang_thai_moi,
            nhan_vien_hien_tai_id = p_nhan_vien_id
        WHERE id = v_don_hang.id;

    ELSE
        RAISE EXCEPTION 'Sự kiện không hợp lệ: %', v_su_kien;
    END IF;

    -- --------------------------------------------------------
    -- GHI NHẬT KÝ SAU KHI CẬP NHẬT THÀNH CÔNG
    -- --------------------------------------------------------
    INSERT INTO nhat_ky_don_hang (
        nhan_vien_id,
        don_hang_id,
        khach_hang_id,
        hanh_dong,
        trang_thai_cu,
        trang_thai_moi,
        minh_chung,
        kho_id,
        ghi_chu,
        vi_do,
        kinh_do,
        thoi_gian
    )
    VALUES (
        p_nhan_vien_id,
        v_don_hang.id,
        v_don_hang.khach_hang_id,
        v_hanh_dong,
        v_trang_thai_cu,
        v_trang_thai_moi,
        p_minh_chung,
        p_kho_id,
        p_ghi_chu,
        p_vi_do,
        p_kinh_do,
        NOW()
    );

    RETURN QUERY
    SELECT
        TRUE,
        v_don_hang.id,
        v_don_hang.ma_van_don::TEXT,
        v_trang_thai_cu,
        v_trang_thai_moi,
        v_hanh_dong,
        v_ten_kho,
        NOW();
END;
$$;

