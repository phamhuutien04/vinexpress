-- 15. TRIGGER TỰ CẬP NHẬT NGÀY SỬA
-- ============================================================

CREATE OR REPLACE FUNCTION cap_nhat_thoi_gian()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.ngay_cap_nhat := NOW();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_khach_hang_cap_nhat
BEFORE UPDATE ON khach_hang
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_kho_hang_cap_nhat
BEFORE UPDATE ON kho_hang
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_nhan_vien_cap_nhat
BEFORE UPDATE ON nhan_vien
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_don_hang_cap_nhat
BEFORE UPDATE ON don_hang
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_xe_cap_nhat
BEFORE UPDATE ON xe
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_chuyen_xe_cap_nhat
BEFORE UPDATE ON chuyen_xe
FOR EACH ROW
EXECUTE FUNCTION cap_nhat_thoi_gian();

CREATE TRIGGER trg_chuyen_xe_chang_cap_nhat
BEFORE UPDATE ON chuyen_xe_chang
FOR EACH ROW
