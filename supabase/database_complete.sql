CREATE OR REPLACE FUNCTION kiem_tra_cay_kho() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE v_cap SMALLINT; v_tinh TEXT; v_tinh_trung_tam TEXT;
BEGIN
  IF NEW.cap_kho = 1 THEN NEW.kho_trung_tam_id := NULL; RETURN NEW; END IF;
  SELECT kh.cap_kho, kv.tinh_thanh INTO v_cap, v_tinh_trung_tam
  FROM kho_hang kh JOIN khu_vuc kv ON kv.id=kh.khu_vuc_id WHERE kh.id=NEW.kho_trung_tam_id;
  SELECT tinh_thanh INTO v_tinh FROM khu_vuc WHERE id=NEW.khu_vuc_id;
  IF NEW.cap_kho <> 2 OR v_cap <> 1 OR v_tinh IS DISTINCT FROM v_tinh_trung_tam THEN
    RAISE EXCEPTION 'Kho cấp 2 phải thuộc kho cấp 1 cùng tỉnh/thành';
  END IF;
  RETURN NEW;
END; $$;
CREATE TRIGGER trg_kiem_tra_cay_kho BEFORE INSERT OR UPDATE OF cap_kho,kho_trung_tam_id,khu_vuc_id
ON kho_hang FOR EACH ROW EXECUTE FUNCTION kiem_tra_cay_kho();

