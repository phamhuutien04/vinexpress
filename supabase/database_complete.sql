-- Chỉ cho phép chặng liên tỉnh giữa hai kho cấp 1.
CREATE OR REPLACE FUNCTION kiem_tra_chang_lien_tinh() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE cap_di SMALLINT; cap_den SMALLINT; tinh_di TEXT; tinh_den TEXT;
BEGIN
 SELECT kh.cap_kho,kv.tinh_thanh INTO cap_di,tinh_di FROM kho_hang kh JOIN khu_vuc kv ON kv.id=kh.khu_vuc_id WHERE kh.id=NEW.kho_di_id;
 SELECT kh.cap_kho,kv.tinh_thanh INTO cap_den,tinh_den FROM kho_hang kh JOIN khu_vuc kv ON kv.id=kh.khu_vuc_id WHERE kh.id=NEW.kho_den_id;
 IF tinh_di IS DISTINCT FROM tinh_den AND (cap_di<>1 OR cap_den<>1) THEN RAISE EXCEPTION 'Chặng liên tỉnh chỉ được đi giữa kho cấp 1'; END IF;
 RETURN NEW;
END; $$;
CREATE TRIGGER trg_kiem_tra_chang_lien_tinh BEFORE INSERT OR UPDATE OF kho_di_id,kho_den_id
ON chuyen_xe_chang FOR EACH ROW EXECUTE FUNCTION kiem_tra_chang_lien_tinh();

